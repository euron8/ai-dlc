G() { git -C "$REPO" "$@"; }
refuse() { printf 'REFUSED %s\n' "$1"; refused=1; }
warn()   { printf 'WARN %s\n' "$1"; }
resolve() { # <ref> -> full sha or empty
  G rev-parse --verify --quiet "$1^{commit}" 2>/dev/null
}
tracked() { # <ref> <path>
  G cat-file -e "$1:$2" 2>/dev/null
}
story_text() { # <ref> <normalised story> -> the story bytes on stdout; 1 if unreadable, 2 if outside
  if tracked "$1" "$2"; then G show "$1:$2"; return 0; fi
  # norm_story contained the DIRECTORY and kept the link name, so an untracked story that is itself
  # a symlink is followed here, hop by hop, and its final target's physical directory is held to
  # the same containment test. A tracked symlink never reaches this: `git show` emits the link string.
  if [ -L "$TOP/$2" ]; then
    local f="$TOP/$2" t d n=0
    while [ -L "$f" ]; do
      n=$((n + 1)); [ "$n" -le 40 ] || { echo "$ME: UNEVALUABLE — the story symlink does not resolve: $2" >&2; return 2; }
      t="$(readlink "$f")" || { echo "$ME: UNEVALUABLE — the story symlink does not resolve: $2" >&2; return 2; }
      case "$t" in /*) f="$t" ;; *) f="${f%/*}/$t" ;; esac
    done
    d="${f%/*}"
    d="$(cd -P "${d:-/}" 2>/dev/null && pwd -P)" || { echo "$ME: UNEVALUABLE — the story symlink's target directory does not resolve: $2" >&2; return 2; }
    case "$d" in
      "$TOP"|"$TOP"/*) ;;
      *) echo "$ME: UNEVALUABLE — the story is a symlink to a file outside the repository top level $TOP: $2 (directory $d)" >&2; return 2 ;;
    esac
  fi
  [ -f "$TOP/$2" ] && { cat "$TOP/$2"; return 0; }
  return 1
}
# norm_story <story> -> the toplevel-relative path on stdout; exit status 2 (with the reason on
# stderr) when it resolves outside the toplevel or cannot be resolved. Containment is decided on
# `pwd -P` of BOTH sides, never on the spelling: a textual prefix strip passes a `/tmp` spelling
# of a `/private/tmp` repo as outside and a `lnk/..` hop as inside.
norm_story() {
  local p="$1" dir base d
  base="${p##*/}"
  case "$base" in ""|.|..) echo "$ME: UNEVALUABLE — story path names no file: $p" >&2; return 2 ;; esac
  case "$p" in */*) dir="${p%/*}" ;; *) dir="." ;; esac
  case "$p" in
    /*) [ -n "$dir" ] || dir=/ ;;
    *) dir="$TOP/$dir" ;;
  esac
  if ! d="$(cd -P "$dir" 2>/dev/null && pwd -P)"; then
    # A relative story whose directory is absent on disk is read at the ref only; it may not
    # climb, because nothing on disk resolves the climb.
    case "$p" in
      /*) echo "$ME: UNEVALUABLE — the story's directory does not resolve: $p" >&2; return 2 ;;
      ../*|*/../*|*/..|./*|*/./*) echo "$ME: UNEVALUABLE — the story's directory does not resolve: $p" >&2; return 2 ;;
    esac
    printf '%s\n' "$p"; return 0
  fi
  if [ "$d" = "$TOP" ]; then printf '%s\n' "$base"; return 0; fi
  case "$d" in
    "$TOP"/*) printf '%s/%s\n' "${d#"$TOP"/}" "$base" ;;
    *) echo "$ME: UNEVALUABLE — the story resolves outside the repository top level $TOP: $p (directory $d)" >&2; return 2 ;;
  esac
}
# ------------------------------------------------------------------------- strategy
strategy_one() { # <ref> <story>
  local ref="$1" story="$2" text rows
  text="$(story_text "$ref" "$story")" || { echo "$ME: UNEVALUABLE — cannot read $story at $ref or on disk" >&2; return 2; }
  # One row per line: id <TAB> case <TAB> kind <TAB> resolves. The header row and the
  # separator row are dropped. A row with fewer than four cells is emitted as
  # `SHORT <TAB> id` when the table's header carries a `Resolves to` column (that row has no
  # cell to resolve and is refused), and dropped otherwise (a table this mode cannot read).
  rows="$(LC_ALL=C awk "$HEADING_AWK"'
    ev_level($0, "Strategy Test IDs") == 2 {on=1; next}
    on && /^## / {exit}
    on && /^[[:space:]]*\|/ {
      line=$0; sub(/^[[:space:]]*\|/, "", line); sub(/\|[[:space:]]*$/, "", line)
      n=split(line, c, "|")
      for (i=1; i<=n; i++) { gsub(/`/, "", c[i]); gsub(/^[[:space:]]+|[[:space:]]+$/, "", c[i]) }
      if (c[1] == "Strategy id") { for (i=1; i<=n; i++) if (c[i] == "Resolves to") hasres=1; next }
      if (c[1] ~ /^:?-+:?$/) next
      if (n < 4) { if (hasres) printf "SHORT\t%s\t\t\n", c[1]; next }
      r=c[4]; for (i=5; i<=n; i++) r=r "|" c[i]
      printf "%s\t%s\t%s\t%s\n", c[1], c[2], c[3], r
    }' <<<"$text")"
  [ -n "$rows" ] || return 0
  local id cs kind res toks tok path rest name src
  while IFS="$(printf '\t')" read -r id cs kind res; do
    if [ "$id" = "SHORT" ]; then
      refuse "short-row $story: ${cs:-<blank id>} has fewer than four cells under a header that carries Resolves to"
      continue
    fi
    if [ -z "$kind" ] || [ -z "$res" ]; then
      refuse "empty-cell $story: $id case ${cs:--} has an empty $( [ -z "$kind" ] && echo Kind || echo 'Resolves to' ) cell"
      continue
    fi
    [ "$kind" = "test" ] || continue
    toks="$(grep -oE '[A-Za-z0-9_./-]+\.py(::[A-Za-z_][A-Za-z0-9_]*)+' <<<"$res")" || toks=""
    [ -n "$toks" ] || continue
    while IFS= read -r tok; do
      path="${tok%%::*}"; rest="${tok#*::}"
      if ! tracked "$ref" "$path"; then
        refuse "node-missing $story: $id case ${cs:--} names $tok, and $path is not tracked at $ref"
        continue
      fi
      src="$(G show "$ref:$path")"
      while [ -n "$rest" ]; do
        name="${rest%%::*}"
        case "$rest" in *::*) rest="${rest#*::}" ;; *) rest="" ;; esac
        if ! grep -qE "^[[:space:]]*((async[[:space:]]+)?def|class)[[:space:]]+${name}[[:space:]]*[(:]" <<<"$src"; then
          refuse "node-missing $story: $id case ${cs:--} names $tok, and $path defines no class or def '$name' at $ref"
          break
        fi
      done
    done <<<"$toks"
  done <<<"$rows"
  return 0
}
# cap_norm <token> -> CN set to the token's toplevel-relative path, return 0; CN empty, return 1
# when it is UNRESOLVABLE. Every relative token, `./` and `../` spellings included, is resolved
# from the TOPLEVEL, never from the story file's directory: `./x` is `x`, as the shipping
# validator always read it, and `a/../b` is `b`. An absolute token is resolved physically: its
# deepest existing ancestor directory through `cd -P` (so a `/tmp` spelling of a `/private/tmp`
# repo, or a symlinked parent, is the same path), then held to the toplevel (itself `pwd -P`).
# `.` and `..` segments are then folded lexically: the captures are read at <frozen> through git,
# where no directory is a symlink. An absolute token under no toplevel of this repository (another
# worktree's path, `/etc/...`) and a token that climbs above the toplevel (any leading `../`) are
# UNRESOLVABLE. The header (HANDOFF MODE) says why `../` is toplevel-relative and that the choice
# is unmeasured.
cap_norm() {
  local t="$1" p d tail seg rest out=""
  CN=""
  case "$t" in
    /*)
      d="${t%/*}"; tail="${t##*/}"
      while [ -n "$d" ] && [ ! -d "$d" ]; do tail="${d##*/}/$tail"; d="${d%/*}"; done
      d="$(cd -P "${d:-/}" 2>/dev/null && pwd -P)" || return 1
      p="${d%/}/$tail"
      case "$p" in "$TOP"/*) p="${p#"$TOP"/}" ;; *) return 1 ;; esac ;;
    *) p="$t" ;;
  esac
  rest="$p"
  while [ -n "$rest" ]; do
    case "$rest" in */*) seg="${rest%%/*}"; rest="${rest#*/}" ;; *) seg="$rest"; rest="" ;; esac
    case "$seg" in
      ""|.) ;;
      ..) [ -n "$out" ] || return 1
          case "$out" in */*) out="${out%/*}" ;; *) out="" ;; esac ;;
      *) out="${out:+$out/}$seg" ;;
    esac
  done
  [ -n "$out" ] || return 1
  CN="$out"
}
# cap_resolve: cap_tokens lines on stdin -> "<red>\t<token>\t<path>", <path> empty when cap_norm
# finds the token UNRESOLVABLE (the empty field is last, so a tab-IFS read keeps the columns).
# "B\t<basename>" lines pass through unchanged.
cap_resolve() {
  local red t
  while IFS="$TAB" read -r red t; do
    [ -n "$t" ] || continue
    if [ "$red" = B ]; then printf 'B\t%s\n' "$t"; continue; fi
    cap_norm "$t" || CN=""
    printf '%s\t%s\t%s\n' "$red" "$t" "$CN"
  done
}
cap_tokens() {
  LC_ALL=C awk -v capx="$CAPX" -v bare="$1" '
  {
    line=$0; l2=line; gsub(/[A-Z0-9]+-[A-Z0-9]+-[A-Z0-9]+(-[A-Z0-9]+)*/, " ", l2)
    red = (l2 ~ /(^|[^A-Za-z])(RED|PROVEN)([^A-Za-z]|$)/) ? 1 : 0
    while (match(line, /[A-Za-z0-9_.\/-]+/)) {
      t=substr(line, RSTART, RLENGTH); line=substr(line, RSTART+RLENGTH)
      sub(/[.]+$/, "", t)
      slash = (t ~ /\//)
      if (t ~ /\.\.\./) continue
      if (!slash && bare != 1) continue
      if (t !~ ("[^/]" capx "$")) continue
      b=t; sub(/.*\//, "", b)
      if (b ~ /^(requirements|constraints)[^\/]*\.txt$/ || b == "CMakeLists.txt" || b ~ /^(LICENSE|robots)\.txt$/) continue
      if (!slash) { print "B\t" t; continue }
      print red "\t" t
    }
  }'
}
# cap_head <replay line number, or empty> reads $hdr (a capture's first 25 lines) and sets CH_SHA
# (the sha as written, empty when none) and CH_DIRTY (1 when ` (+dirty)` follows it). The replay
# block's own `head:` (the first after its header) first, else the first `head:` in the 25 lines.
# The head WARN and the render both read this one function.
cap_head() {
  local rl="$1" h=""
  [ -n "$rl" ] && h="$(tail -n +"$rl" <<<"$hdr" | LC_ALL=C grep -oE "$HEAD_RE" | head -n 1)"
  [ -n "$h" ] || h="$(LC_ALL=C grep -oE "$HEAD_RE" <<<"$hdr" | head -n 1)"
  h="${h#head:}"; h="${h#"${h%%[![:space:]]*}"}"
  CH_SHA="${h%%[!0-9a-f]*}"; CH_DIRTY=0
  case "$h" in *"(+dirty)") CH_DIRTY=1 ;; esac
}
dar_strip() { LC_ALL=C awk "$DAR_STRIP_AWK"; }
# dar_span <field> -> the field as a code span; one holding a backtick in a double-backtick span.
dar_span() {
  case "$1" in *'`'*) printf '`` %s ``' "$1" ;; *) printf '`%s`' "$1" ;; esac
}
# render_dar: sets DAR_RENDER (the block, no trailing newline) and DAR_NCOUNT (lines carrying a
# count) for the story in $TEXT (stripped) at $FROZEN. In the current shell, never `$( )`.
render_dar() {
  local caps p hdr rl cmd cnt fcv fcp ln
  caps="$(list_captures)"
  fcv="$(bash "$HE_SELF/record-only-diff.sh" label 'Full-collection run:' <<<"$TEXT" 2>/dev/null)" || fcv=""
  fcp=""
  [ -z "$fcv" ] || fcp="$(cap_tokens 0 <<<"$fcv" | cap_resolve | awk -F'\t' '$3 != "" {print $3}')"
  DAR_RENDER="$DAR_OPEN"; DAR_NCOUNT=0
  if [ -n "$caps" ]; then
    while IFS= read -r p; do
      # LC_ALL=C on every tr/grep here: BSD tr in a UTF-8 locale aborts on one non-UTF-8 byte.
      hdr="$(G show "$FROZEN:$p" 2>/dev/null | head -n 25 | LC_ALL=C tr -d '\r')"
      rl="$(LC_ALL=C awk '/^mutation-red replay$/{print NR; exit}' <<<"$hdr")"
      cap_head "$rl"
      cmd="$(LC_ALL=C grep -E "$CMD_RE" <<<"$hdr" | head -n 1)"
      cmd="${cmd%"${cmd##*[![:space:]]}"}"
      ln="- $(dar_span "$p") — "
      if [ -n "$CH_SHA" ]; then
        if [ "$CH_DIRTY" = 1 ]; then ln="${ln}head $(dar_span "$CH_SHA (+dirty)")"; else ln="${ln}head $(dar_span "$CH_SHA")"; fi
      else ln="${ln}head (none)"; fi
      if [ -n "$cmd" ]; then ln="$ln — $(dar_span "$cmd")"; else ln="$ln — command (none)"; fi
      # D3: a count only for a capture the Full-collection run: value cites, never a replay capture.
      if [ -n "$fcp" ] && grep -qxF -- "$p" <<<"$fcp"; then
        cnt="$(G show "$FROZEN:$p" 2>/dev/null | LC_ALL=C tr -d '\r' | LC_ALL=C grep -E '[0-9]+[[:space:]]+(passed|failed)([^A-Za-z]|$)' | tail -n 1)"
        cnt="${cnt#"${cnt%%[![:space:]]*}"}"; cnt="${cnt%"${cnt##*[![:space:]]}"}"
        [ -z "$rl" ] || cnt=""
        if [ -n "$cnt" ]; then ln="$ln — $(dar_span "$cnt")"; DAR_NCOUNT=$((DAR_NCOUNT + 1)); fi
      fi
      DAR_RENDER="$DAR_RENDER"$'\n'"$ln"
    done <<<"$caps"
  fi
  DAR_RENDER="$DAR_RENDER"$'\n'"$DAR_CLOSE"
}
dar_eval() {
  local blk nb open story_blk diff
  render_dar
  blk="$(LC_ALL=C awk "$DAR_BLOCK_AWK" <<<"$TEXT_RAW")"
  nb="$(awk -F'\t' '$1 == "N" {print $2}' <<<"$blk")"; open="$(awk -F'\t' '$1 == "N" {print $3}' <<<"$blk")"
  DAR_STATE=""; DAR_MSG=""
  if [ "${nb:-0}" -ge 2 ]; then
    DAR_STATE=dup; DAR_MSG="dar-heads-duplicate $STORY: $nb capture-heads blocks at ${FROZEN:0:12}; keep one, the verbatim stdout of --render-dar"
    return
  fi
  if [ "${nb:-0}" -eq 0 ]; then
    if [ "$DAR_RENDER" = "$DAR_OPEN"$'\n'"$DAR_CLOSE" ]; then DAR_STATE=none; return; fi
    DAR_STATE=missing; DAR_MSG="dar-heads-missing $STORY: the story cites a capture and carries no capture-heads block at ${FROZEN:0:12}; paste the stdout of 'validate-handoff-evidence.sh --render-dar $STORY HEAD' under ## Dev Agent Record and never retype a head"
    return
  fi
  story_blk="$(awk -F'\t' '$1 == "L" {print substr($0, 3)}' <<<"$blk")"
  diff="$(HE_A="$story_blk" HE_R="$DAR_RENDER" LC_ALL=C awk 'BEGIN { na = split(ENVIRON["HE_A"], A, "\n"); nr = split(ENVIRON["HE_R"], R, "\n"); n = (na > nr) ? na : nr
    for (i = 1; i <= n; i++) {
      a = (i <= na) ? A[i] : "<none>"; r = (i <= nr) ? R[i] : "<none>"
      if (a != r) { printf "line %d of the block: story [%s] render [%s]", i, a, r; exit }
    } }')"
  if [ "$open" = 1 ] && [ -z "$diff" ]; then diff="the block is never closed by a column-0 $DAR_CLOSE"; fi
  if [ -n "$diff" ]; then
    DAR_STATE=stale; DAR_MSG="dar-heads-stale $STORY: the capture-heads block differs from the render at ${FROZEN:0:12}, $diff; re-run --render-dar and paste its stdout verbatim"
    return
  fi
  DAR_STATE=ok
}
# list_captures: the --list-captures set for the story in $TEXT (stripped) at $FROZEN, on stdout.
list_captures() {
  local lc_toks lc_full lc_bare lc_dirs p d
  lc_toks="$(cap_tokens 1 <<<"$TEXT" | cap_resolve)"
  # Every token through cap_norm, the handoff arms' normaliser: `./` and absolute spellings of a
  # tracked capture list under their toplevel spelling; an UNRESOLVABLE token (a leading `../`)
  # lists nothing.
  lc_full="$(awk -F'\t' '$1 != "B" && $3 != "" {print $3}' <<<"$lc_toks" | LC_ALL=C sort -u)"
  lc_bare="$(awk -F'\t' '$1 == "B" {print $2}' <<<"$lc_toks" | LC_ALL=C sort -u)"
  {
    if [ -n "$lc_full" ]; then
      while IFS= read -r p; do tracked "$FROZEN" "$p" && printf '%s\n' "$p"; done <<<"$lc_full"
    fi
    if [ -n "$lc_bare" ] && [ -n "$lc_full" ]; then
      lc_dirs="$(awk '{sub(/\/[^\/]*$/, ""); print}' <<<"$lc_full" | LC_ALL=C sort -u)"
      while IFS= read -r d; do
        # --full-tree: the pathspec is toplevel-relative whatever directory -C names.
        G ls-tree --full-tree "$FROZEN" -- "$d/" 2>/dev/null \
          | HE_BARE="$lc_bare" awk -F'\t' 'BEGIN { n = split(ENVIRON["HE_BARE"], L, "\n"); for (i = 1; i <= n; i++) want[L[i]] = 1 }
              { split($1, m, " "); if (m[2] != "blob") next; b = $2; sub(/.*\//, "", b); if (b in want) print $2 }'
      done <<<"$lc_dirs"
    fi
  } | LC_ALL=C sort -u
}
# SD: every smoke pathspec diff runs from the top level, where `<rev>:<path>` resolves, so `-C <subdirectory>`
# cannot re-root the surface or the surface-file pathspec and acquit the range.
SD() { git -C "$TOP" diff --name-only --no-renames "$@"; }
# smoke_tokens: story text on stdin -> "<removal 0|1>\t<path>" per backticked PATH token inside the
# level-2 `## Smoke Test Updates` section(s), fences stripped, CR stripped (header: the token grammar).
smoke_tokens() {
  LC_ALL=C awk "$HEADING_AWK"'
    {
      m = ""
      if ($0 ~ /^[ \t]*```/) m = "```"
      else if ($0 ~ /^[ \t]*~~~/) m = "~~~"
      if (sfc == "" && m != "") { sfc = m; next }
      if (sfc != "") { if (m == sfc) sfc = ""; next }
    }
    # ev_level strips a trailing CR itself; no token rule reads one, so a CRLF story needs no other strip.
    ev_level($0, "Smoke Test Updates") == 2 { on = 1; next }
    /^##?[ \t]/ { on = 0 }
    !on { next }
    {
      line = $0; low = tolower(line)
      rm = (low ~ /(^|[^a-z])(removed|deleted)([^a-z]|$)/) ? 1 : 0
      while (match(line, /`[^`]+`/)) {
        t = substr(line, RSTART + 1, RLENGTH - 2); line = substr(line, RSTART + RLENGTH)
        if (t ~ /[ \t]/ || t !~ /\// || t ~ /^\// || t ~ /=|:\/\/|[*?[]/) continue
        sub(/::.*$/, "", t); sub(/:[0-9]+$/, "", t)
        if (t !~ /\//) continue
        print rm "\t" t
      }
    }'
}
smoke_arms() { # <base> <frozen> <story> -> SMOKE/SKIP verdict lines and REFUSED lines; 2 when unreadable
  local sb="$1" sf="$2" st="$3" txt toks rmv tok ty chg ed globs lglobs hits hrc seen=" " hit=""
  txt="$(story_text "$sf" "$st")" || { echo "$ME: UNEVALUABLE — cannot read $st at $sf or on disk" >&2; return 2; }
  toks="$(smoke_tokens <<<"$txt")"
  # (m1) SMOKE-LISTED-ABSENT: every path token names a blob at <frozen>, unless its line says removed.
  if [ -n "$toks" ]; then
    while IFS="$TAB" read -r rmv tok; do
      [ -n "$tok" ] || continue
      case "$seen" in *" $tok "*) continue ;; esac
      seen="$seen$tok "
      # A CANDIDATE TEST FILE only: its last segment carries a `.` (a trailing `/` leaves it empty) and
      # it is not a tree at <frozen>. Every other token is prose to m1, never listed-absent.
      case "${tok##*/}" in *.*) ;; *) continue ;; esac
      ty="$(G cat-file -t "$sf:$tok" 2>/dev/null)"
      [ "$ty" = blob ] && continue
      [ "$ty" = tree ] && continue
      [ "$rmv" = 1 ] && continue
      refuse "smoke-listed-absent $st: \`$tok\` in ## Smoke Test Updates is not tracked at ${sf:0:12}; commit it, correct the path, or say on its line that it was removed"
    done <<<"$toks"
  fi
  chg="$(SD "$sb" "$sf" 2>/dev/null)" \
    || { printf 'UNEVALUABLE SMOKE-SURFACE (git diff %s..%s failed)\n' "${sb:0:12}" "${sf:0:12}"; return 2; }
  # The surface's PATH is the contract's `consumer_smoke_surface_file:` at <base> (header: SURFACE).
  smoke_surface_path "$sb" || return $?
  if [ -z "$SMOKE_SURFACE" ]; then
    refuse "smoke-surface-unevaluable $st: $SMOKE_SURFACE_LC at ${sb:0:12} declares consumer_smoke_surface_file: with no path; an empty path names the whole tree, so declare the surface file's path (or delete the key for $SMOKE_SURFACE_DEFAULT) outside the story's range"; return 0
  fi
  # SMOKE-SURFACE-EDITED: the surface is the gate's input, read at <base>; the story may not move it.
  ed="$(SD "$sb" "$sf" -- "$SMOKE_SURFACE" 2>/dev/null)" \
    || { printf 'UNEVALUABLE SMOKE-SURFACE (git diff %s..%s -- %s failed)\n' "${sb:0:12}" "${sf:0:12}" "$SMOKE_SURFACE"; return 2; }
  if [ -n "$ed" ]; then
    refuse "smoke-surface-edited $st: $SMOKE_SURFACE changed in ${sb:0:12}..${sf:0:12}; the smoke surface is read at the story's base, so change it outside the story's range"
  fi
  # The surface is read at <base> (srev), never at <frozen>.
  local srev="$sb"
  if ! G cat-file -e "$srev:$SMOKE_SURFACE" 2>/dev/null; then
    printf 'SKIP SMOKE-SURFACE (undeclared: no %s at %s)\n' "$SMOKE_SURFACE" "${srev:0:12}"; return 0
  fi
  globs="$(G show "$srev:$SMOKE_SURFACE" 2>/dev/null | LC_ALL=C awk '{ sub(/\r$/, ""); sub(/^[ \t]+/, ""); sub(/[ \t]+$/, "") } $0 == "" || /^#/ { next } { print }')"
  if [ -z "$globs" ]; then printf 'SKIP SMOKE-SURFACE (empty: write globs or none)\n'; return 0; fi
  # `none` is read in any case: a capitalised `None` left uncased is no lone `none`, reaches the matches-nothing guard below and REFUSES smoke-surface-unevaluable.
  lglobs="$(tr '[:upper:]' '[:lower:]' <<<"$globs")"
  if [ "$lglobs" = none ]; then printf 'SMOKE NO-SURFACE (declared none in %s at %s)\n' "$SMOKE_SURFACE" "${srev:0:12}"; return 0; fi
  # SMOKE-SURFACE-UNEVALUABLE: the surface lines, as one pathspec set, listed against <base> (a diff from the
  # empty tree, so the pathspec grammar is exactly the (m2) diff's). A line git rejects (`:(bogus)x`, an
  # unclosed `:(top`) exits 128 with no output, and a set matching no path at <base> AND none at <frozen>
  # (`none.`, `` `none` ``, a typo) is empty: either would read below as "no surface path changed", so both
  # REFUSE, and the handoff's other refusals still stand (exit 1, never the exit 2 a caller reads as
  # "nothing checked"). A set matching nothing at <base> but something at <frozen> is a surface the story
  # creates (a greenfield directory) and goes on to (m2). The set is judged whole: a typo line beside a
  # matching line is not refused.
  local et lst flst="" lrc frc
  et="$(G hash-object -t tree /dev/null)"
  set -f
  # shellcheck disable=SC2086 -- one pathspec per line, split on newlines only, never globbed by the shell.
  lst="$(IFS='
'; SD "$et" "$sb" -- $globs 2>/dev/null)"; lrc=$?
  set +f
  if [ "$lrc" -ne 0 ]; then
    # Which failure: the same pathspecs over <empty tree>..<empty tree> read no object, so they fail there only
    # when git rejects a pathspec (stderr wording varies by form: `Invalid pathspec magic`, `Missing ')'`,
    # `are incompatible`, `is outside repository`, `attr spec must not be empty`). Passing there, the listing
    # failed on an object at <base> (`unable to read tree`): UNEVALUABLE, exit 2 unless an arm already refused.
    set -f
    # shellcheck disable=SC2086 -- one pathspec per line, split on newlines only, never globbed by the shell.
    if (IFS='
'; SD "$et" "$et" -- $globs >/dev/null 2>&1); then
      set +f
      printf 'UNEVALUABLE SMOKE-SURFACE (git diff <empty tree>..%s -- <surface> failed on an object, exit %s; the pathspecs parse)\n' "${sb:0:12}" "$lrc"; return 2
    fi
    set +f
    refuse "smoke-surface-unevaluable $st: git rejected a pathspec in $SMOKE_SURFACE at ${srev:0:12} (exit $lrc); correct the line outside the story's range"; return 0
  fi
  if [ -z "$lst" ]; then
    set -f
    # shellcheck disable=SC2086 -- one pathspec per line, split on newlines only, never globbed by the shell.
    flst="$(IFS='
'; SD "$et" "$sf" -- $globs 2>/dev/null)"; frc=$?
    set +f
    # The pathspecs passed at <base>; a failure here is a git failure on the resolved <frozen>.
    if [ "$frc" -ne 0 ]; then
      printf 'UNEVALUABLE SMOKE-SURFACE (git diff <empty tree>..%s -- <surface> failed, exit %s)\n' "${sf:0:12}" "$frc"; return 2
    fi
  fi
  if [ -z "$lst$flst" ]; then
    refuse "smoke-surface-unevaluable $st: the lines of $SMOKE_SURFACE at ${srev:0:12} match no path tracked at ${sb:0:12} or at ${sf:0:12}; write pathspecs that match the surface, or a lone none, outside the story's range"; return 0
  fi
  # (m2) SMOKE-NOT-UPDATED: a range touching the surface must change a listed path token.
  set -f
  # shellcheck disable=SC2086 -- one pathspec per line, split on newlines only, never globbed by the shell.
  hits="$(IFS='
'; SD "$sb" "$sf" -- $globs 2>/dev/null)"; hrc=$?
  set +f
  # The same pathspecs passed at <base> above; a failure here is a git failure on resolved refs, as at `chg`.
  if [ "$hrc" -ne 0 ]; then
    printf 'UNEVALUABLE SMOKE-SURFACE (git diff %s..%s -- <surface> failed, exit %s)\n' "${sb:0:12}" "${sf:0:12}" "$hrc"; return 2
  fi
  if [ -z "$hits" ]; then
    printf 'SMOKE OK (no smoke-surface path changed in %s..%s)\n' "${sb:0:12}" "${sf:0:12}"; return 0
  fi
  if [ -n "$toks" ]; then
    while IFS="$TAB" read -r rmv tok; do
      [ -n "$tok" ] || continue
      if grep -qxF -- "$tok" <<<"$chg"; then hit="$tok"; break; fi
    done <<<"$toks"
  fi
  if [ -n "$hit" ]; then
    printf 'SMOKE OK (%s changed in range, beside smoke-surface path %s)\n' "$hit" "$(head -n 1 <<<"$hits")"
  else
    refuse "smoke-not-updated $st: ${sb:0:12}..${sf:0:12} changes smoke-surface path $(head -n 1 <<<"$hits") and no path token in ## Smoke Test Updates is changed in that range; add or update the smoke test and list it there"
  fi
  return 0
}
