glob_resolves() { # <token> -> 0 when EVERY brace alternative matches >=1 file tracked at FROZEN
  local g="$1" pats p n any pre rest body post alt files
  pats="$g"
  case "$g" in *"{"*"}"*)
    pre="${g%%\{*}"; rest="${g#*\{}"; body="${rest%%\}*}"; post="${rest#*\}}"; pats=""
    while [ -n "$body" ]; do
      alt="${body%%,*}"
      case "$body" in *,*) body="${body#*,}" ;; *) body="" ;; esac
      pats="$pats$pre$alt$post"$'\n'
    done ;;
  esac
  while IFS= read -r p; do
    [ -n "$p" ] || continue
    any=0
    files="$(G ls-tree -r --name-only "$FROZEN" -- "${p%/*}/" 2>/dev/null)"
    while IFS= read -r n; do
      # $p unquoted on purpose: it is the glob being matched.
      case "$n" in $p) any=1; break ;; esac
    done <<<"$files"
    [ "$any" -eq 1 ] || return 1
  done <<<"$pats"
  return 0
}
# (o) DAR-HEADS (header: HANDOFF MODE). The --render-dar --check arm, folded; `dar-heads-missing`
# keyed on git records (dar_legacy), never on the story's text.
# dar_legacy -> DL set to "bind" (the story's first commit descends from VADD), "legacy" or
# "undecidable", and DL_WHY. Every git call's stderr is discarded and its output staged, never piped.
dar_legacy() {
  local vlog vadd slog sfirst
  DL=undecidable; DL_WHY=""
  vlog="$(G log -S--render-dar --reverse --format=%H "$FROZEN" -- scripts/ai-dlc/validate-handoff-evidence.sh core/scripts/validate-handoff-evidence.sh 2>/dev/null)" || vlog=""
  vadd="${vlog%%$'\n'*}"
  if [ -z "$vadd" ]; then DL_WHY="no commit on ${FROZEN:0:12}'s history adds --render-dar to the installed validator (shallow history, or the engine is not committed)"; return; fi
  slog="$(G log --diff-filter=A --reverse --format=%H "$FROZEN" -- "$STORY" 2>/dev/null)" || slog=""
  sfirst="${slog%%$'\n'*}"
  if [ -z "$sfirst" ]; then DL_WHY="no commit on ${FROZEN:0:12}'s history adds $STORY"; return; fi
  if G merge-base --is-ancestor "$vadd" "$sfirst" 2>/dev/null; then DL=bind
  else DL=legacy; DL_WHY="the story's first commit ${sfirst:0:12} predates ${vadd:0:12}, the commit that added --render-dar"; fi
}
