#!/usr/bin/env bash
# validate-handoff-evidence.sh — refuse a dev handoff whose evidence a reviewer would
# bounce, before gate 1 is dispatched, and refuse a Strategy Test IDs cell that no longer
# resolves, before the sprint-review gate opens.
#
#   validate-handoff-evidence.sh [-C <repo>] [--gate2] <story-file> <base> <frozen>
#   validate-handoff-evidence.sh [-C <repo>] --strategy <ref> <story-file>...
#   validate-handoff-evidence.sh [-C <repo>] --list-captures <story-file> <frozen>
#   validate-handoff-evidence.sh [-C <repo>] --render-dar <story-file> <frozen> [--check]
#   validate-handoff-evidence.sh [-C <repo>] --smoke <story-file> <base> <frozen>
#
# RENDER-DAR MODE prints the CAPTURE-HEADS BLOCK for the story read at <frozen>: the head, command
# and (for the full-collection capture only) count of every capture, rendered from the captures so
# the dev never retypes them into the Dev Agent Record. One block on stdout:
#   <!-- capture-heads: generated by validate-handoff-evidence.sh --render-dar; do not edit -->
#   - `<path>` — head `<sha as written>` — `<command line>` [— `<count line>`]
#   <!-- /capture-heads -->
# The capture set is exactly the --list-captures set (list_captures, one reader), in its LC_ALL=C
# order. Per capture, read at <frozen>: the command is the first of its first 25 lines that arm
# (a)'s reader (CMD_RE) accepts, so a replay capture renders `mutation-red replay` when that line
# comes first; `command (none)` when none does; trailing blanks are trimmed from the command line, as
# from the count line. The head is cap_head's, the reader the head WARN
# uses (the replay block's own `head:` first, else the first `head:` in 25 lines), with a following
# ` (+dirty)` kept; `head (none)` when there is none. A COUNT renders ONLY for a capture the
# `Full-collection run:` label's value cites (record-only-diff.sh's label grammar): its LAST line
# matching RUN-SHAPE's `<n> passed|failed` count grammar, never guessed when absent. No other capture
# gets a count, and neither does a REPLAY capture (one carrying a column-0 `mutation-red replay` line
# in its first 25) even when that value cites it, so a mutation-RED capture's `1 failed` never renders. A field holding a backtick is
# rendered in a double-backtick span with one space inside each end (`` x ``); a field holding a
# run of two backticks is not representable and renders the same way, broken. An empty capture set
# renders the two marker lines only. Exit 0 rendered, 2 UNEVALUABLE (as --list-captures).
#   --check exits 0 when the story at <frozen> carries exactly one block (both markers at column 0
#   and outside ``` / ~~~ fences; the open marker is any column-0 line beginning
#   `<!-- capture-heads:` or `<!-- capture-heads `, so a hand-edited opener is a stale block, not a
#   missing one) byte-identical to the render (trailing CR ignored), or carries no block and cites
#   no capture. Else exit 1 with one REFUSED line: `dar-heads-stale` (the first differing block
#   line, both sides; also an opener never closed), `dar-heads-missing` (a capture cited, no block),
#   `dar-heads-duplicate` (two blocks or more). NOT CIRCULAR: every citation reader strips the block
#   region (dar_strip) before cap_tokens, so the block's own backticked paths and commands are never
#   citations; a capture cited ONLY inside the block is not cited, and pasting the render changes no
#   input the render reads.
#
# SMOKE MODE (BL-845) runs ONLY the smoke arms below (smoke_arms), never the status, row, heading,
# capture or run-record arms: the row arm refuses correct stories at the gate-2 shas (MEASURED,
# bookkeeping arms, below). The lead runs it at the gate-2 go-signal, before QA is dispatched;
# handoff mode runs the same function at every gate-1 handoff. It is the MECHANICAL half of
# gate-validation.md Check 11 ("section exists and lists files", "the files exist"); the judgment
# half (the tests correspond to the story's user-facing change, the test type matches the change
# type) is not read here and stays the gate's. The smoke surface is defined once, in
# gate-validation.md Check 11, **Smoke surface.**; this script reads it, never restates it.
#   SECTION. The story's level-2 `## Smoke Test Updates` section(s), by the shared HEADING_AWK
#   ev_level grammar (`## Smoke Test Updates (dev)` counts), read at <frozen> as handoff mode
#   reads the story, code fences stripped, a trailing CR stripped, ending at the next `#`/`##` heading.
#   PATH TOKEN. A backticked token with no whitespace that contains `/`, does not start with `/`,
#   and carries none of `=`, `://`, `*`, `?`, `[`; a `::...` suffix (a pytest node id) and then a
#   trailing `:<digits>` (a line number) are stripped. So `/api/x`, `KEY=http://h/x`,
#   `web/tests/*.spec.js`, a shell command with spaces and a bare basename are not paths and are
#   not read. A line carrying the word `removed` or `deleted` marks its tokens as REMOVALS.
#   (m1) SMOKE-LISTED-ABSENT. A CANDIDATE TEST FILE that is not tracked at <frozen>. A path token is
#       a candidate only when its last path segment contains a `.` (so a token ending in `/` is
#       not one) and `git cat-file -t` at <frozen> does not answer `tree`; every other token
#       (`web/`, `test-results/`, `tests/e2e`, a dotted directory) is prose to m1 and is ignored,
#       never refused. A removal is not refused. Known
#       acquittal: the removal word is read on the LINE, so "`x` was not removed" acquits an absent
#       `x`; under (m2) a removal helps only if the path is in the range anyway.
#   SURFACE PATH. The file the layer contract declares as `consumer_smoke_surface_file:`, the
#       contract itself read at <BASE> through git (`.claude/skills/ai-dlc/layer-contract.yaml`, else
#       the distribution's `core/skills/ai-dlc/layer-contract.yaml`). No contract at <base>, or a
#       contract without the key: `docs/smoke-surface.txt`. The key present with an EMPTY value REFUSES
#       `smoke-surface-unevaluable` (an empty path names the root tree). `docs/smoke-surface.txt` below
#       stands for whichever path this resolves to.
#   SURFACE. `docs/smoke-surface.txt`, read at <BASE> through git, never the working tree: one git pathspec per
#       line, `#` comments and blank lines ignored. Each line reaches `git diff --name-only <base>
#       <frozen> -- <lines>` as ONE argument, split on newlines only and never globbed by the shell
#       (`set -f`), so git's own pathspec magic holds: `web/src/*.js` matches below `web/src/`, a
#       line may carry a space, and `:(exclude)<path>` or `:!<path>` removes a generated file from
#       the surface. Every smoke diff runs from the repository top level (`git -C <toplevel>`), so a
#       `-C <subdirectory>` reads the same pathspecs as `-C <toplevel>`. Four states, each its own
#       stdout verdict:
#         absent at <base>              -> `SKIP SMOKE-SURFACE (undeclared: no docs/smoke-surface.txt at <base12>)`
#         only `none` (plus comments)   -> `SMOKE NO-SURFACE (declared none ...)`, (m2) not run; `none`
#                                          is read in any case (`None`, `NONE`), never as a pathspec
#         no pathspecs and no `none`    -> `SKIP SMOKE-SURFACE (empty: write globs or none)`
#         pathspecs                     -> (m2) runs: `SMOKE OK (...)` or a REFUSED line
#       (m1) and SMOKE-SURFACE-EDITED run in every state. A SKIP is never an OK.
#   SMOKE-SURFACE-UNEVALUABLE. Before (m2), the surface lines are listed as one pathspec set against
#       <base> (`git diff --name-only <empty tree> <base> -- <lines>`, the (m2) diff's own grammar). A
#       line git rejects (`:(bogus)x`, an unclosed `:(top`, `../x`: exit 128, no output) and a set that
#       matches NO path tracked at <base> AND none at <frozen> (`none.`, `` `none` ``, a typo such as
#       `web/scr/**`) both REFUSE `smoke-surface-unevaluable`, and the run goes on to exit 1 with every
#       other arm's refusals: either would otherwise read as "no surface path changed" and give SMOKE OK.
#       The surface TEXT is still read at <base>; <frozen> is listed only so that a surface naming a
#       directory the story itself creates (`web/app/**`, absent at <base>) is not refused. The guard
#       judges the line SET: a typo line beside a matching line is not refused, and its coverage is
#       silently lost (known acquittal). An exclude-only surface matches every path it does not name,
#       so it does not trip this. The case-folded lone `none` is NO-SURFACE above and never reaches it.
#       Which listing failure is a rejected pathspec is decided by running the same pathspecs over
#       <empty tree>..<empty tree>, which reads no object: they fail there only when git rejects one
#       (git's stderr wording differs per form, so it is not matched). A listing that fails while the
#       pathspecs parse failed on an object (a corrupt or missing tree at <base>) and is UNEVALUABLE.
#       UNEVALUABLE (exit 2). A smoke `git diff` that fails on resolved refs (the range diff, the
#       surface-file diff, the surface listing at <base> or <frozen> whose pathspecs parse, or the (m2)
#       diff) prints `UNEVALUABLE SMOKE-SURFACE (<reason>)` on stdout. Exit 2 is "nothing checked" to
#       every caller (implementation.md gate 1 and gate 2 dispatch on it), so it is taken only when no
#       arm has refused: a REFUSED line already printed, in --smoke or in handoff mode (the smoke arms
#       or a missing record-only-diff.sh sibling), exits 1.
#   SMOKE-SURFACE-EDITED. The surface file is in `git diff --name-only <base> <frozen>`: the
#       story may not move the gate's own input.
#   (m2) SMOKE-NOT-UPDATED. `git diff --name-only <base> <frozen> -- <pathspecs>` is non-empty and
#       NO path token of the section is itself in `git diff --name-only <base> <frozen>` (a removal
#       shows there too). Wording-free: `None`, `N/A`, prose, and a token naming an unchanged file
#       all refuse alike. Known acquittal: ANY changed listed path satisfies it, whether or not it
#       tests the surface that changed; that correspondence is the judgment half.
#   NARROWING. The predicate was first "no backticked token and no `none, <reason>`": the reference
#   consumer's s320 4.2 dispatched body (`None. \`scripts/test-aws-smoke.sh\` asserts no HODL
#   surface ...`) carries a tracked backticked path, so it would have ACQUITTED the motivating case.
#   A none-form-first-word predicate was then dropped for this wording-free one. Over graph s317-s320
#   (776 section blobs, 91 distinct bodies): 7 of 96 backticked tokens are basenames and are not read;
#   436 bodies are empty (the template placeholder), accepted over a non-surface range.
#   MEASURED (this release's script, read only from committed graph refs at graph `main` 91a665334028): 85 gate-2 passes over 57 stories in s317-s320, out of 107 QA review files (the census EXCLUDED 22 passes whose merged review file carries no base or range; unmeasured, not clean): 2 refusals, both true (s320 4.2 gate-2 p1, s319 4.4 gate-2 p1), 0 false. Before the m1 narrowing, in this release's development, the same set gave 13 refusals, 11 false (8 on directory or extensionless prose tokens; 3 from a wrong derived base or a generated schema file, the latter remedied by an exclude pathspec).
#   MEASURED gate-1 handoff mode (this release's script, read only from committed graph refs at graph `main` 91a665334028; s320 reviews read from graph ref `origin/ai-dlc/carry-over/s319-closeout-smoke-green` 3bd62256f, the only ref carrying them): 132 gate-1 passes over 53 stories out of 149 code-review files (the census EXCLUDED 17: no stated base, no reviewed-sha, or a non-story review; unmeasured, not clean). As graph is today, with no surface file: 0 smoke refusals. With a surface file (each story's first-pass base, test files excluded): 10 refusals, 10 true, 0 false.
#
# LIST-CAPTURES MODE prints, one per line, every CAPTURE (grammar below) the story cites, the story
# read at <frozen> as handoff mode reads it. Each token goes through the handoff arms' normaliser
# (cap_norm, below), and a path is printed only when `git cat-file -e <frozen>:<path>` passes,
# toplevel-relative with no `./` (the spelling `git diff --numstat` prints): a `./` or absolute
# spelling of a tracked capture prints its toplevel path; UNRESOLVABLE (a leading `../`, a path
# outside the repository) and phantom tokens print
# nothing. A bare basename the story names
# with a capture extension prints every file tracked at <frozen> with that basename directly inside
# one of the story's capture directories (the directories of its full-path captures, as arm (c)
# reads them). Deduplicated, sorted under LC_ALL=C. Exit 0 (empty output allowed), 2 UNEVALUABLE.
# partition-review-diff.sh --exclude-captures reads this list.
#
# <story-file> is relative to the repository's top level or absolute, in both modes. norm_story
# turns every story argument into ONE toplevel-relative path before anything reads it: an
# absolute path's directory and the toplevel are each resolved with `cd -P`/`pwd -P`, and the
# directory must be the toplevel or under it (a `/tmp`-spelled path in a `/private/tmp` repo,
# a linked worktree's own absolute path, and a symlinked directory inside the tree all resolve
# to the same relative path). A relative path is resolved against the toplevel the same way.
# A path that resolves outside the toplevel (`stories/../../x.md`, `<root>/lnk/../x.md` with
# `lnk` a symlink out of the tree, another worktree's absolute path) is UNEVALUABLE, exit 2.
# Without this an absolute story was never `tracked` at the ref: handoff mode refused it as
# story-untracked and skipped the heading arm, and strategy mode read the WORKING TREE's
# copy instead of the ref's. The normalised story is read at <frozen> (or <ref>) when tracked
# there, else from disk. Exit 0 clean (WARN lines allowed), 1 at least one REFUSED line,
# 2 UNEVALUABLE (a ref that does not resolve, a story file that cannot be read or that
# resolves outside the repository).
#
# WHY. In the reference consumer's s317-s318, 22 of 33 implementation rework verdicts were
# evidence or bookkeeping, not code: a capture with no command line, a RED capture left
# gitignored and so absent from the commit the reviewer reads, a glob cited where a file
# was meant. Each cost a full review pass to find. The checks below are the mechanical part
# of that class; a reviewer still grades what the captures SAY.
#
# HANDOFF MODE — five refusals; no WARN line changes the exit.
#
#   A CAPTURE is a path token the story cites that contains a `/`, does not contain `...`,
#   and ends in `.txt`, `.log` or `.out`. Bare basenames and elided paths cannot be
#   resolved and are not read; that is an acquittal, stated here so nobody mistakes it for
#   coverage. `.md` evidence files are not captures (they carry their own prose header).
#   Every capture token is NORMALISED (cap_norm, shared with --list-captures) to its toplevel
#   spelling before any arm reads it: every relative token resolves from the TOPLEVEL (`./x` is
#   `x`, `a/../b` is `b`), an absolute token under this repository's toplevel (physical,
#   `pwd -P`) becomes toplevel-relative, and `.`/`..` segments fold. An absolute token under no
#   toplevel of this repository (another worktree's path, `/etc/...`) or one that climbs above the
#   toplevel (any leading `../`) is UNRESOLVABLE. So an absolute- or `./`-spelled tracked capture is
#   judged by (a)/(j)/WARN like its toplevel spelling, and (b) no longer calls such a tracked RED
#   capture untracked; a leading-`../` citation is never skipped silently (CAPTURE-UNRESOLVED or
#   (b) names it). WHY TOPLEVEL: graph's committed stories carry 0 `./` tokens and 2 `../` tokens,
#   both in s320 3.3, and neither base (toplevel or story directory) resolves either `../` token.
#   Both choices are therefore UNMEASURED, taken for consistency with the shipping validator, which
#   strips `./` and resolves the remainder from the toplevel; a later batch with a discriminating
#   token re-decides them. The subject of this normaliser is the silent skip, not a change to what
#   `./` means.
#   CAPTURE-UNRESOLVED (WARN, never a refusal, exit unchanged). A cited capture that (b) does not
#   refuse and that is UNRESOLVABLE (`resolves outside the repository`) or not tracked at <frozen>
#   (`not tracked at <sha12>`) prints one `WARN capture-unresolved <token>: <reason>` line. An
#   untracked path that a `.gitignore` TRACKED AT <frozen> ignores prints nothing: that is the
#   gitignored full-suite capture (b) acquits below. Measured on graph s319's four affected
#   stories (1-2, 1-5, 3-1, 4-3, 27 passes): every untracked toplevel-spelled citation was
#   ignored by the frozen `.gitignore` (`test-results/`, `*.txt`), so the exemption is the
#   whole of that set, and the 4-3 citation into another worktree WARNs.
#
#   (a) NO-COMMAND. A capture added or modified in <base>..<frozen> whose first 25 lines
#       carry no command line: one beginning `$ `, `command: `, `cmd=`, `sha=<sha> cmd=`,
#       or validate-mutation-red.sh's `mutation-red replay`. A `cmd=` in mid-line (pytest
#       output, an xdist banner) is not a header. dev.md `## QA Handoff Evidence`
#       prescribes `$ <command>` first, then a line carrying `head: <sha>`. A capture outside
#       the range is not this story's and is not read, so an UNTRACKED capture escapes (a)
#       by construction — (b) owns the RED case and CAPTURE-UNRESOLVED (above) the rest, a
#       WARN unless the frozen `.gitignore` ignores it. <base> is the gate-1
#       partition manifest's `base` (the parent of the dev's first commit) on EVERY handoff,
#       rework included (implementation.md), so on a rework (a) reads every capture the story's
#       range touched, not only the rework's; (b) and (c) read the whole story regardless. RANGE
#       WARN: base == frozen (an empty range, so (a) reads nothing) or a base that is not an
#       ancestor of frozen.
#   (b) RED-UNTRACKED. A capture cited AS a mutation-RED capture that is not tracked at
#       <frozen>. A capture is cited as RED when the line citing it carries `RED` or `PROVEN`
#       (upper case, the verdict words) as a word, not as a segment of an all-caps hyphenated
#       identifier of three or more segments (`CO-S318-...-RED-AT-...`); `mutation-RED` still
#       counts; or its basename carries `red`, `mutation` or `mut` as a `-`/`_`/`.`-delimited
#       word. A gitignored full-suite capture cited without those words is NOT refused: a
#       full-collection run is not a RED.
#       MEASURED on the reference consumer, read-only, over its 1145 stories at 036a69cc8 plus
#       67 s317-s320 stories at the carry-over ref: blanking those identifiers changes the RED
#       flag on 23 lines, every one an identifier (s320 3.3:77, 3.2:93), and on 0 verdict lines.
#       Adding `-` to the boundary class instead drops 349 verdict lines (`mutation-RED`,
#       `RED-before-fix`, ...).
#   (c) GLOB-CITED. A token carrying `*` or `{`…`}` cited as a capture path — its last
#       segment ends in a capture extension, or its directory is the directory of a
#       capture the same story cites — of which some brace alternative matches NO file
#       tracked at <frozen>. A glob whose every alternative matches a committed file names
#       evidence the reviewer can read and is not refused. `{id}` in an API route or
#       `{REPO_ROOT}/x.sh` is not a capture path and is not refused.
#   (j) REPLAY-PREAMBLE. An in-range capture (a)'s range reads, whose first 25 lines carry
#       `mutation-red replay`, with a `$ ` line above the first such line that is not the line
#       right above it. validate-mutation-red.sh prints its `$ ` line immediately above its
#       replay header, so an earlier `$ ` line is hand-written (dev.md: commit the capture as
#       the script wrote it). A replay with no `$ ` line above it is accepted: the engine
#       before the `$ ` line was added printed none. A capture without the replay line is not read by (j).
#   (m) K-UNQUOTED. An in-range capture (a)'s range reads, whose first 25 lines carry a `$ ` line
#       passing `-k` an UNQUOTED multi-word expression: `-k <word> (or|and|not) <word>`, the first
#       word not opening with `"` or `'`. The shell splits it, so pytest receives `-k <word>` and
#       the rest as paths, and the line does not replay the run it labels. Refused `k-unquoted`.
#       Quoted (`-k "a or b"`) and single-word (`-k foo`) expressions are not read. MEASURED on the
#       reference consumer, read-only, over 100 gate-1 passes of s317-s319 (519 in-range captures,
#       402 `$ ` lines): 4 hits, every one a true positive (s319 3-1 p4 and p6, the mutation-RED
#       captures `ac8-generation-compare`, `ac9-nonarray`, `ac9-redirect`, raised by the reviewer
#       at `3-1-code-review-p6.md:741`). FP set empty, with no narrowing needed. That count is over
#       EVERY in-range capture; this arm reads only the ones the story CITES, as (a) does, so the
#       shipped arm refuses 2 of the 4 (`ac8-generation-compare` at p4 and p6). The story at p6
#       cites neither ac9 capture, so (m) does not read them.
#   (n) PLACEHOLDER (WARN, never a refusal, exit unchanged). An in-range capture (a)'s range
#       reads, whose first 25 lines carry a `$ ` line with an unexpanded `<name>` placeholder
#       (`<[A-Za-z_-]+>`): one `WARN placeholder <capture>: ...` line per placeholder. Narrowing,
#       same population as (m): every `<x>` first; then `<redacted>` exempt (credential hygiene:
#       a capture must not carry the secret it elides); then `<base-worktree>` exempt, the one
#       remaining hit (s319 3-3 `test-results/s319-3-3-evidence/lint-base.txt:1`), which its
#       reviewer accepted. FP 0 after that. A WARN because an enumerated FP set a reviewer
#       accepted is correct data, and a WARN cannot wedge a correct handoff.
#   WARN. A capture's `head:` sha is missing, does not resolve, or names a tree that
#       differs from <frozen> outside the cited captures and the story file. For a replay
#       capture the sha is the first `head:` after the replay header, falling back to the
#       first in the 25 lines when the block carries none. Never a
#       refusal: a capture taken at the content head and committed in a records commit
#       after it is the normal shape.
#   (o) DAR-HEADS. Handoff mode runs the --render-dar --check arm on the story at <frozen> and
#       folds its REFUSED line into its own: `dar-heads-stale` and `dar-heads-duplicate` always
#       refuse. `dar-heads-missing` (a capture cited, no block) is decided from git records, never
#       from the story's text (an omission must not exempt itself), the way
#       validate-carried-findings.sh's PRE-MIGRATION test is: VADD is the EARLIEST commit on
#       <frozen>'s history whose diff changes the count of `--render-dar` in
#       `scripts/ai-dlc/validate-handoff-evidence.sh` or `core/scripts/validate-handoff-evidence.sh`
#       (`log -S --reverse`, first line), and the story's first commit is the earliest that adds it
#       (`--diff-filter=A`). That first commit descending from VADD: REFUSED. Not descending from it
#       (a story authored before the pull): `WARN dar-heads-missing` (LEGACY), exit unchanged.
#       No VADD (shallow history, a consumer that never commits `scripts/ai-dlc/`) or no first
#       commit: `WARN dar-heads-missing` (UNDECIDABLE), never a refusal. That last state is an
#       ACQUITTAL, stated here so nobody mistakes it for coverage: a consumer that does not commit
#       its installed engine WARNs on every story, forever.
#       The (k) record-only exemption gains one acceptance: a `Full-collection run:` value that
#       records no run is still accepted when it carries `counts: capture-heads block`, the block
#       is fresh (--check 0) and the render gave a count line to a capture that value cites. A value
#       naming only a capture path, or the phrase with no fresh block, is held to (k) as before; so is
#       one citing only a replay capture, which the render never counts (REFUSED full-collection-none
#       on a range that is not record-only).
#
# HANDOFF MODE, BOOKKEEPING — three refusals and a SKIP line, every one read AT <frozen> via
# `git show`, never the working tree.
#
#   (g) STATUS-NOT-REVIEW. The story's status is not `review`. The grammar is
#       sprint-status.sh's (frontmatter `status:` first, `**Status:**` only for a file with no
#       frontmatter; both regexes from schemas/sprint-status.json), reached through its
#       `story-status --ref` mode, which must sit beside this script.
#   (h) STATUS-YAML-MISMATCH. The story's status disagrees with its row in the IMPLEMENTATION
#       view of the canonical sprint-status yaml. Never the planning view: it lagged at three
#       APPROVED gate-1 shas on the reference consumer (s318 2.1, s317 2.2, s317 1.2).
#   STATUS-MISSING. The story is committed at <frozen> and no grammar finds a status in it.
#   STORY-UNTRACKED. The story file is not tracked at <frozen>: the reviewer reads the commit.
#   --gate2 (handoff mode only, first operand after -C) SKIPS arm (h) at a gate-2 go-signal sha, where the
#       row arm refuses correct stories (MEASURED, below), printing `SKIP STATUS (--gate2: ...)` in its place.
#       Every other arm runs unchanged; without the flag arm (h) behaves as before.
#   SKIP STATUS (<reason>). No yaml, no row, or the sibling missing or failing: printed on
#       stdout, never a refusal, never silent. The reason is the sibling's stderr, never a data line.
#   Lines are read with a trailing CR stripped, so a CRLF story is read as the same story, and
#   under LC_ALL=C: BSD awk in a UTF-8 locale ABORTS on one non-UTF-8 byte (`towc: multibyte
#   conversion failure`) and the heading arm then reads nothing. The grammar is ASCII-only.
#   (i) HEADING-DEMOTED. One of the four evidence headings dev.md requires at `## ` appears only
#       deeper (`### Smoke Test Updates`) or only at level 1. Code fences are stripped. The
#       heading grammar is one awk function shared with strategy mode: `## <heading>` followed by
#       whitespace and any text (`## Rename Verification (dev)`) is that heading at level 2.
#
# HANDOFF MODE, RUN RECORD — two refusals and a LEGACY line, read from the story text the evidence
# arms read. A LABEL is a line outside ``` / ~~~ fences that begins, at column 0 or after one `- `
# or `* ` bullet, with the label text exactly; the rest of the line is its VALUE (it may be empty:
# the invocation and counts may follow on the next lines, and grading them stays the reviewer's).
