#!/usr/bin/env node
/*
 * gen-architecture-index.js — ai-dlc maintainer / pipeline tool
 *
 * Emits a compact slice-navigation index for a large living architecture doc so
 * dev/qa agents can locate and slice-read the section(s) they need instead of
 * whole-reading the file (SKILL.md Rule 25(b)). One consumer's architecture.md
 * reached ~506K tokens; whole-reading it on every dispatch was the single
 * largest read cost in the pipeline. This index is the discoverability backstop
 * dev/qa consult when a story's `architecture_refs` frontmatter is absent.
 *
 * DETERMINISTIC BY DESIGN: headings, anchors, and line ranges are extracted
 * mechanically; the one-line summary is the first prose line under each heading,
 * truncated. There is NO LLM call and NO whole-doc summarization — authoring the
 * index by summary would re-incur the very whole-read cost it exists to avoid.
 *
 * Anchors match GitHub's slugger (lowercase, strip non-word except `-` and
 * space, spaces -> `-`, dedupe with `-N`), so `#<anchor>` links resolve.
 *
 * Headings inside fenced code blocks (``` / ~~~) are skipped — code comments
 * like `# Uniswap v3 ...` are not document sections.
 *
 * Usage:
 *   node scripts/ai-dlc/gen-architecture-index.js \
 *     [--doc docs/architecture.md] [--out docs/architecture-index.md] \
 *     [--h3] [--stdout]
 *
 * By default only H2 sections are indexed — enough to locate a section and
 * slice-read its line range, and cheap. `--h3` adds H3 rows for finer-grained
 * navigation (larger index). Default paths are consumer-relative (run from the
 * consumer repo root).
 */

'use strict';
const fs = require('fs');
const path = require('path');

function parseArgs(argv) {
  const opts = { doc: 'docs/architecture.md', out: 'docs/architecture-index.md', stdout: false, h3: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--doc') opts.doc = argv[++i];
    else if (a === '--out') opts.out = argv[++i];
    else if (a === '--h3') opts.h3 = true;
    else if (a === '--stdout') opts.stdout = true;
    else if (a === '-h' || a === '--help') opts.help = true;
    else { throw new Error(`unknown argument: ${a}`); }
  }
  return opts;
}

// GitHub-style anchor slugger with per-document dedupe.
function makeSlugger() {
  const seen = new Map();
  return function slug(title) {
    let s = title
      .toLowerCase()
      .replace(/[^\w\- ]+/g, '') // drop anything not word char, hyphen, or space
      .replace(/ /g, '-');
    const n = seen.get(s) || 0;
    seen.set(s, n + 1);
    return n === 0 ? s : `${s}-${n}`;
  };
}

// First non-empty, non-heading, non-fence prose line under a heading, truncated.
function firstSummary(lines, startIdx, endIdx, maxLen) {
  let inFence = false;
  for (let i = startIdx; i < endIdx; i++) {
    const line = lines[i];
    const t = line.trim();
    if (/^(```|~~~)/.test(t)) { inFence = !inFence; continue; }
    if (inFence) continue;
    if (t === '' || /^#{1,6}\s/.test(t)) continue;
    if (/^(<!--|\|)/.test(t)) continue; // skip HTML comments and table rows
    const oneLine = t.replace(/\s+/g, ' ');
    return oneLine.length > maxLen ? oneLine.slice(0, maxLen - 1).trimEnd() + '…' : oneLine;
  }
  return '';
}

function extractHeadings(text) {
  const lines = text.split('\n');
  const headings = [];
  let inFence = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const t = line.trim();
    if (/^(```|~~~)/.test(t)) { inFence = !inFence; continue; }
    if (inFence) continue;
    const m = /^(#{2,3})\s+(.*\S)\s*$/.exec(line); // H2 and H3 only
    if (m) headings.push({ level: m[1].length, title: m[2].trim(), line: i + 1, idx: i });
  }
  return { headings, lines };
}

function buildIndex(doc, includeH3) {
  const text = fs.readFileSync(doc, 'utf8');
  const { headings, lines } = extractHeadings(text);
  const slug = makeSlugger(); // slug ALL headings so anchors match GitHub even when H3 rows are hidden
  const rows = headings.map((h, k) => {
    const nextIdx = k + 1 < headings.length ? headings[k + 1].idx : lines.length;
    return {
      level: h.level,
      title: h.title,
      anchor: slug(h.title),
      line: h.line,
      summary: firstSummary(lines, h.idx + 1, nextIdx, 120),
    };
  }).filter((r) => includeH3 || r.level === 2);
  return { rows, totalLines: lines.length, docPath: doc };
}

function render({ rows, totalLines, docPath }) {
  const out = [];
  out.push('# Architecture Index');
  out.push('');
  out.push(`> Auto-generated by \`scripts/ai-dlc/gen-architecture-index.js\` from \`${docPath}\` (${totalLines} lines, ${rows.length} sections).`);
  out.push('> Slice-navigation only (SKILL.md Rule 25(b)): locate a section here, then Read that section by line range — do NOT whole-read the architecture doc.');
  out.push('> Do not hand-edit; regenerated on every architecture-step update.');
  out.push('');
  out.push('| Line | Section | Anchor | Summary |');
  out.push('|---|---|---|---|');
  for (const r of rows) {
    const indent = r.level === 3 ? '&nbsp;&nbsp;↳ ' : '';
    const title = r.title.replace(/\|/g, '\\|');
    const summary = (r.summary || '').replace(/\|/g, '\\|');
    out.push(`| ${r.line} | ${indent}${title} | \`#${r.anchor}\` | ${summary} |`);
  }
  out.push('');
  return out.join('\n');
}

function main() {
  let opts;
  try { opts = parseArgs(process.argv.slice(2)); }
  catch (e) { console.error(e.message); process.exit(2); }
  if (opts.help) {
    console.log('Usage: node scripts/ai-dlc/gen-architecture-index.js [--doc PATH] [--out PATH] [--stdout]');
    return;
  }
  if (!fs.existsSync(opts.doc)) {
    console.error(`architecture doc not found: ${opts.doc}`);
    process.exit(1);
  }
  const index = buildIndex(opts.doc, opts.h3);
  const md = render(index);
  if (opts.stdout) {
    process.stdout.write(md);
  } else {
    fs.mkdirSync(path.dirname(opts.out), { recursive: true });
    fs.writeFileSync(opts.out, md);
    console.error(`wrote ${opts.out}: ${index.rows.length} sections from ${index.totalLines}-line ${opts.doc}`);
  }
}

main();
