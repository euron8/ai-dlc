#!/bin/bash
#
# AI/DLC Pipeline Continuation Hook
#
# PURPOSE
# Enforces Rule 3 (Never stall the pipeline) when the pipeline is in
# autonomous mode. Respects user-initiated pauses via a flag file
# written by the UserPromptSubmit hook (ai-dlc-pause.sh).
#
# DECISION ORDER (first match wins)
# 1. pause flag exists               -> allow stop (user is driving)
# 2. no snapshot exists              -> allow stop (no active pipeline)
# 3. rapid-fire limit exceeded       -> allow stop (stall confirmed)
# 4. default                         -> block stop (force Rule 3 continue)
#
# RAPID-FIRE DETECTION (time-based, replaces stop_hook_active check)
# Tracks the timestamp of each block and a counter of consecutive
# rapid-fire blocks. If two blocks occur within 30 seconds of each
# other, they are counted as the same stall attempt. After 3 such
# rapid-fire blocks, the hook backs off and allows the stop.
#
# Why time-based instead of stop_hook_active? When the pipeline
# invokes multiple bmad skills in sequence (common in Discovery
# phase: brainstorming, advanced-elicit, adversarial-review),
# each skill's turn ends with a Stop event and Claude Code sets
# stop_hook_active=true on the next turn. The stop_hook_active
# signal cannot distinguish "genuine loop" from "legitimate
# multi-skill progression." A 30-second threshold cleanly
# separates the two: a real bmad skill takes far longer than
# 30 seconds, while a tight stall-and-retry happens in seconds.
#
# PAUSE CONTRACT
# The pause flag is created by:
#   1. ai-dlc-pause.sh on any user message during an active pipeline, OR
#   2. The lead itself when it has a legitimate intentional pause
#      (HARD_BLOCK awaiting operator decision per Rule 11(a), handoff
#      per Rule 2, gate failure, Production Validation Checkpoint).
# The lead interprets user intent and deletes the flag when the user
# wants to resume autonomous execution. This hook never creates or
# deletes the flag; it only reads it.
#
# DESIGN PRINCIPLE
# This hook prevents UNINTENTIONAL stalls. It does not prevent
# INTENTIONAL pauses. The lead has authority to pause when it knows
# it should pause (per AI/DLC rules). The flag file is the lead's
# mechanism to express that intent. The hook respects the flag
# regardless of who created it.
#
# OUTPUT
# - State: _bmad-output/pipeline-block-state.txt (2 lines:
#   last-block epoch timestamp, consecutive rapid-fire count)
# - Appends to: _bmad-output/pipeline-continuation-log.md
# - JSON to stdout on block: decision + reason
# - Exit 0 in all cases (block is in the JSON body)
#
# INSTALL
# 1. Place at .claude/hooks/ai-dlc-continue.sh
# 2. chmod +x .claude/hooks/ai-dlc-continue.sh
# 3. Add to .claude/settings.json hooks:
#      "Stop": [
#        {
#          "hooks": [{
#            "type": "command",
#            "command": "$CLAUDE_PROJECT_DIR/.claude/hooks/ai-dlc-continue.sh"
#          }]
#        }
#      ]
# 4. Restart Claude Code
# 5. Verify with /hooks

set -u

# -----------------------------------------------------------------------------
# Configuration
# -----------------------------------------------------------------------------
PROJECT_DIR="${CLAUDE_PROJECT_DIR:-.}"
SNAPSHOT_FILE="${PROJECT_DIR}/_bmad-output/pipeline-snapshot.md"
LOG_DIR="${PROJECT_DIR}/_bmad-output"
LOG_FILE="${LOG_DIR}/pipeline-continuation-log.md"
PAUSE_FLAG="${LOG_DIR}/pipeline-paused.flag"
STATE_FILE="${LOG_DIR}/pipeline-block-state.txt"
# Beat-liveness marker written by scripts/ai-dlc/wait-for-deliverable.sh while a
# backgrounded wait-beat is genuinely sleeping (Check 2b, v0.81.0). Same dir and
# default as the script's AI_DLC_STATE_DIR (_bmad-output).
BEAT_MARKER="${LOG_DIR}/.beat-inflight"

# Rapid-fire thresholds
RAPID_WINDOW_SECONDS=30
MAX_RAPID_BLOCKS=3

# -----------------------------------------------------------------------------
# Read hook input
# -----------------------------------------------------------------------------
INPUT=$(cat)
SESSION_ID=$(echo "$INPUT" | jq -r '.session_id // empty')
TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
NOW=$(date +%s)

# -----------------------------------------------------------------------------
# Seed log header if needed
# -----------------------------------------------------------------------------
mkdir -p "$LOG_DIR"
if [ ! -s "$LOG_FILE" ]; then
  cat > "$LOG_FILE" <<'EOF'
# Pipeline Flow Log

Records pipeline-level events: user pauses, Rule 3 enforcement, operator
acknowledgement denials, and rapid-fire stall detection. Generated by AI/DLC
hook scripts. Rotated per sprint at retro close (Rule 25(c)).

Event types:

- `USER_PAUSE`: user sent a message; pipeline paused via flag file
- `BLOCKED`: Stop event blocked; Rule 3 enforcement forced continue
- `ALLOWED_BY_PAUSE`: Stop event allowed because pause flag exists
- `ACK_DENIED`: a pipeline-advancing tool call was DENIED because an operator
  message was outstanding and unacknowledged (Rule 29)
- `BACKOFF`: rapid-fire stop attempts detected; stall confirmed

Retro reviews this log to assess pipeline flow:

- High USER_PAUSE counts mean the user intervened often (normal for
  interactive sprints, concerning if unexpected)
- High BLOCKED counts mean Rule 3 enforcement is doing work; without
  the hook the pipeline would have stalled
- BACKOFF entries indicate the pipeline actually got stuck and the
  hook exhausted its retry budget. Investigate the transcript around
  each BACKOFF to find the upstream cause.

Counting entries: one event is one `## <timestamp> -- <EVENT>` line. Count with
`grep -c '^## .*-- <EVENT>'`. A bare `grep -c <EVENT>` also matches this header,
which mentions every event name, so it over-reports — and the inflated number is
plausible enough that nothing about the result signals it counted documentation.

---

EOF
fi

# -----------------------------------------------------------------------------
# Check 0: Handoff resume-prompt guard
# -----------------------------------------------------------------------------
# Minimum mechanism (Rule 26(c)).
#   Failure caught: the operator asks for a handoff and the turn ENDS without a
#     copy-pasteable `/ai-dlc resume` block. The successor session then has no
#     entry line and the operator hand-writes one. A prose mandate
#     (`steps/handoff.md` step 4) did not hold on its own; this moves emission to
#     the harness. Presence alone is insufficient — a `/ai-dlc resume` mentioned in
#     prose, or in a blockquote with no delimiter lines, is not copy-pasteable — so
#     the guard checks FORMAT: the command line must sit BETWEEN two delimiter
#     lines.
#   False-positive cost: one extra turn when the operator's message merely mentions
#     handoff without requesting one. It self-clears through the rapid-fire backoff
#     below (MAX_RAPID_BLOCKS), so it can never wedge the pipeline.
#   Removal condition: retire when two consecutive sprints record zero
#     handoff-emission misses, or when the resume block is generated rather than
#     hand-authored.
#
# THE DELIMITER IS `-{4,}`, NOT AN EXACT COUNT, AND THAT IS THE WHOLE LESSON.
# The reference consumer carried this guard for months matching EXACTLY six hyphens
# (`^------$`) while `steps/handoff.md` step 4 has ALWAYS mandated four (`----`).
# Six-hyphen appears nowhere in core, at any sha. So the guard fired on handoffs
# that were CORRECT per the rulebook: the lead emitted `----` as instructed, got
# blocked, read a block message telling it to use `------`, and complied with the
# HOOK instead of the RULE. The enforcer quietly overruled the rule it was written
# to enforce — a check that fires on compliance, which is worse than no check.
# The invariant that matters is "the command line is delimited for copy-paste",
# never the hyphen count. Accept four or more; quote the rulebook's own template.
#
# Fail-open: any transcript parse failure skips this check entirely.
TRANSCRIPT=$(echo "$INPUT" | jq -r '.transcript_path // empty')
HANDOFF_STATE="${LOG_DIR}/handoff-guard-state.txt"
if [ -n "$TRANSCRIPT" ] && [ -f "$TRANSCRIPT" ]; then
  LAST_USER=$(jq -rs '[.[]|select(.message.role=="user")|.message.content|(if type=="string" then . else (map(select(.type=="text")|.text)|join(" ")) end)]|map(select(length>0))|last // ""' "$TRANSCRIPT" 2>/dev/null || echo "")
  # LAST_ASST is reconstructed with join("") (NOT " "): the format check below is
  # line-anchored, and a streaming split of one text block into chunks can land a
  # boundary mid-line — join(" ") then corrupts a `----` marker into `-- --` and the
  # lead's own well-formed block false-blocks. join("") rejoins contiguous text so
  # marker lines survive. LAST_USER keeps join(" ") (substring regex, spacing-tolerant).
  LAST_ASST=$(jq -rs '[.[]|select(.message.role=="assistant")|.message.content|(if type=="string" then . else (map(select(.type=="text")|.text)|join("")) end)]|map(select(length>0))|last // ""' "$TRANSCRIPT" 2>/dev/null || echo "")

  # Match REQUEST-shaped phrasings only — "handoff"/"hand off" as a VERB, a terse
  # standalone "handoff", or "continue in a new session". Do NOT match incidental
  # NOUN mentions ("the handoff prompt", "handoff guard", the injected pipeline-control
  # context): those are discussion, not a request, and a bare-substring regex fires on
  # every one of them and spams the operator with a spurious resume prompt. The second
  # grep excludes any message that IS a resume prompt or talks ABOUT the mechanism.
  if echo "$LAST_USER" | grep -qiE 'hand[ -]off (this|it|to|the (sprint|pipeline|work|session))|hand(ing)? (this|it) off|\b(do|create|prepare|need|want|start|begin|let'\''s|please) (a |an |the )?hand[ -]?off\b|^[[:space:]]*hand[ -]?off[[:space:]]*$|continue in a (new|fresh) session|pick (this|it) up in a (new|fresh) session' \
     && ! echo "$LAST_USER" | grep -qiE '/ai-dlc|acknowledge handoff|handoff (resume|guard|prompt|protocol)|resume prompt|pipeline control'; then

    RESUME_OK=$(printf '%s' "$LAST_ASST" | awk '
      /^[[:space:]]*-{4,}[[:space:]]*$/ { marks++; if (marks==1){opened=1;sawcmd=0} else if (marks>=2 && sawcmd){ok=1}; next }
      opened && /^[[:space:]]*\/ai-dlc[[:space:]]+resume[[:space:]]*$/ { sawcmd=1 }
      END { print (ok?"1":"0") }')

    if [ "$RESUME_OK" != "1" ]; then
      H_LAST=0; H_CNT=0
      if [ -f "$HANDOFF_STATE" ]; then
        H_LAST=$(sed -n '1p' "$HANDOFF_STATE" 2>/dev/null); H_CNT=$(sed -n '2p' "$HANDOFF_STATE" 2>/dev/null)
        [[ "$H_LAST" =~ ^[0-9]+$ ]] || H_LAST=0; [[ "$H_CNT" =~ ^[0-9]+$ ]] || H_CNT=0
      fi
      if [ $((NOW - H_LAST)) -lt "$RAPID_WINDOW_SECONDS" ]; then H_CNT=$((H_CNT + 1)); else H_CNT=1; fi
      if [ "$H_CNT" -le "$MAX_RAPID_BLOCKS" ]; then
        echo "$NOW" > "$HANDOFF_STATE"; echo "$H_CNT" >> "$HANDOFF_STATE"
        {
          echo "## ${TIMESTAMP} -- HANDOFF_GUARD_BLOCK (${H_CNT}/${MAX_RAPID_BLOCKS})"
          echo "- Session: ${SESSION_ID}"
          echo "- Handoff requested but the turn ends with no delimited /ai-dlc resume block"
          echo ""
        } >> "$LOG_FILE"
        jq -n --arg r "HANDOFF GUARD: the operator requested a handoff, but this turn ends WITHOUT a copy-pasteable resume prompt. Per steps/handoff.md step 4, emit exactly this, and nothing else -- no narrated body:

\`\`\`
----
/ai-dlc resume
----
\`\`\`

The \`/ai-dlc resume\` line MUST sit BETWEEN two delimiter lines (four or more hyphens, each on its own line). A blockquote is not a delimiter, and a bare mention in prose is not copy-pasteable. Finalize the pipeline snapshot first (step 3) if you have not -- state lives in the snapshot, not the resume line." '{decision:"block",reason:$r,suppressOutput:true}'
        exit 0
      fi
      rm -f "$HANDOFF_STATE"   # backoff exhausted: allow stop (possible false positive)
    else
      rm -f "$HANDOFF_STATE"   # well-formed resume block present: handoff satisfied
    fi
  fi
fi

# -----------------------------------------------------------------------------
# Check 0b: the adversarial cycle STOPPED (Rule 8)
# -----------------------------------------------------------------------------
# Minimum mechanism (Rule 26(c)).
#   Failure caught: an adversarial cycle reaches a state where another pass cannot help --
#     it DIVERGED (the repair is injecting defects into text a previous pass had already
#     cleared) or it STALLED (a nonzero MAJOR held at zero CRITICAL, pass after pass) --
#     and the lead runs another pass anyway. Rule 8 says stop and escalate. Check 24 reads
#     the state, but Check 24 runs at the GATE, after the cycle is over, so the one signal
#     that means STOP had no teeth at the only moment it mattered.
#   Measured: a live cycle stamped DIVERGENT_HARD_BLOCK at pass 15 and the lead ran pass 16;
#     it stamped DIVERGENT_HARD_BLOCK again at pass 17. Between them MAJORs went 1 -> 4 and
#     CRITICALs began appearing in PRIOR scope. Earlier in the SAME cycle it had held
#     0 CRITICAL / 1 MAJOR across passes 11-14 -- a stall, four passes long, and nothing
#     spoke.
#   False-positive cost: one operator adjudication on a cycle that was going to need one.
#   Removal condition: retire when two consecutive sprints record zero STOP states.
#
# THIS HOOK IS NOT THE ENFORCER, AND v0.57.0's MISTAKE WAS THINKING IT WAS.
# `Stop` fires only when the lead YIELDS -- and Rule 3, plus this very hook's Check 2, exist
# to make the lead never yield. A lead that dispatches pass N+1 in the same turn as pass N's
# join never triggers a Stop event, so this check never runs. It fired on the reference
# consumer by LUCK: the lead happened to present its results and stop. An enforcer that
# depends on the failure pausing to let itself be caught is not an enforcer.
# The teeth are in `ai-dlc-acknowledge.sh` (PreToolUse), which can deny the dispatch itself.
# This check's job is narrower and still worth doing: SURFACE the escalation to the operator
# -- raise the pause flag, block the stop once, and write the flow-log entry -- so a human
# learns about it in the same turn it happens.
#
# NO ADJUDICATION HERE (Rule 26, and v0.54.3's "one predicate, two implementations, and the
# tool wins"). This hook used to scrape `verdict:` out of the newest file with awk, and it
# picked that file with `ls -t` -- by MTIME, not by pass number, which is `order_key()`'s
# original bug reintroduced in a different file nine releases later. It now asks the
# validator, which owns ordering, and reads an exit code.
#   mtime picks the SERIES  -- "which cycle is live" is a RECENCY question. Correct.
#   the VALIDATOR picks the PASS -- "which pass is last" is an ORDERING question. Not mtime.
ADVERSARIAL_STOP="${LOG_DIR}/.adversarial-stop"
ART_DIR="${LOG_DIR}/planning-artifacts"
CONVERGENCE_VALIDATOR="${PROJECT_DIR}/scripts/ai-dlc/validate-adversarial-convergence.sh"

CYCLE_STATE=""; CYCLE_RC=0; CYCLE_PASS=""
NEWEST_PASS="$(ls -t "${ART_DIR}"/*adversarial*p*.md 2>/dev/null | head -1)"
if [ -n "$NEWEST_PASS" ]; then
  if [ ! -f "$CONVERGENCE_VALIDATOR" ]; then
    # A partial install must not SILENTLY disable the hard block. That is the
    # `core/git-hooks/`-at-a-dead-path failure -- an enforcer at a path nothing reads, and
    # nothing saying so for two minor releases. Leave a trace retro's Rule 25(c) audit reads.
    {
      echo "## ${TIMESTAMP} -- ADVERSARIAL_STATE_UNADJUDICABLE"
      echo "- Session: ${SESSION_ID}"
      echo "- scripts/ai-dlc/validate-adversarial-convergence.sh is MISSING; the Rule 8 stop state"
      echo "  cannot be adjudicated and the divergence/stall hard block is NOT armed."
      echo ""
    } >> "$LOG_FILE"
  else
    SERIES="$(printf '%s' "$NEWEST_PASS" | sed -E 's/(pass|p)[0-9]+\.md$//')"
    # Pass the transcript so RESOLVED requires a VERIFIED operator citation (arm F6): the stop
    # state must not self-heal on a resolution the operator never authorized. Fails open when
    # no transcript is readable (acknowledge.sh, PreToolUse, is where the dispatch is denied).
    CYCLE_ARGS=(--series "$SERIES" --cycle-state)
    [ -n "$TRANSCRIPT" ] && [ -r "$TRANSCRIPT" ] && CYCLE_ARGS+=(--transcript "$TRANSCRIPT")
    OUT="$(bash "$CONVERGENCE_VALIDATOR" "${CYCLE_ARGS[@]}" 2>/dev/null)"
    CYCLE_RC=$?
    CYCLE_STATE="$(printf '%s' "$OUT" | cut -f1)"
    CYCLE_PASS="$(printf '%s' "$OUT" | cut -f2)"
  fi
fi

# Self-healing GC. `.divergence-raised` was written and never removed by anything -- it
# survived the cycle, the sprint, and the retro rotation. State that only ever accumulates
# is a stale-flag bug waiting for its turn. Any turn the cycle is NOT stopped, the record
# of the stop goes away.
if [ "$CYCLE_RC" -eq 0 ] && [ -f "$ADVERSARIAL_STOP" ]; then
  rm -f "$ADVERSARIAL_STOP"
fi

# Idempotent by (state, pass). The operator clearing the flag IS the adjudication, and this
# must not fight it -- but a NEW stop, on a NEW pass, is a new escalation and raises again.
if [ "$CYCLE_RC" -eq 3 ] && [ "$(cat "$ADVERSARIAL_STOP" 2>/dev/null)" != "${CYCLE_STATE}	${CYCLE_PASS}" ]; then
  printf '%s\t%s\n' "$CYCLE_STATE" "$CYCLE_PASS" > "$ADVERSARIAL_STOP"
  printf '%s: %s\n' "$CYCLE_STATE" "$(basename "$CYCLE_PASS")" > "$PAUSE_FLAG"
  {
    echo "## ${TIMESTAMP} -- ADVERSARIAL_STOP"
    echo "- Session: ${SESSION_ID}"
    echo "- ${CYCLE_STATE} at $(basename "$CYCLE_PASS"); pipeline paused (Rule 8)"
    echo ""
  } >> "$LOG_FILE"

  if [ "$CYCLE_STATE" = "DIVERGENT" ]; then
    WHAT="\`$(basename "$CYCLE_PASS")\` stamps \`verdict: DIVERGENT_HARD_BLOCK\`: it found CRITICALs in scope a previous pass had ALREADY cleared. Those are defects the REPAIR injected, and the next pass only finds the next wave."
  else
    WHAT="The cycle has held a nonzero MAJOR at ZERO CRITICAL for pass after pass. It is neither converging nor diverging -- it is STALLED. Each repair rewrites the prose around a claim nobody verified, and the next pass falsifies the rewrite with one more counterexample. Passes are buying counterexamples, not convergence."
  fi

  # THE SENTENCE THAT USED TO STAND HERE READ: "Do NOT dispatch another adversarial pass,
  # and do NOT clear the pause flag to get past this."
  #
  # It was false, and it was the deadlock. The flag CANNOT be made un-clearable -- Bash is
  # the deliberate escape hatch (see ai-dlc-acknowledge.sh: "Allowing Bash is what makes
  # deadlock impossible") -- so this prose was trying to enforce something the mechanism
  # deliberately cannot, while arm D of Check 24 was simultaneously REQUIRING the terminal
  # clean pass that this text FORBADE. The lead, correctly reading both, concluded that no
  # legal move existed and parked the pipeline on an escalation.
  #
  # The exit is real. It is a RESOLUTION, and it is now a file the validator reads.
  jq -n --arg r "RULE 8 -- THE ADVERSARIAL CYCLE HAS STOPPED (${CYCLE_STATE}). ${WHAT}

ANOTHER PASS IS NOT THE REMEDY, and the pipeline is PAUSED until the operator adjudicates.

THE EXIT:  STOP -> ADJUDICATE -> RESOLVE -> VERIFY

1. STOP. No further pass on the artifact as it stands. (You cannot dispatch one: the
   PreToolUse hook will deny it, and it will keep denying it until step 3 is done.)
2. ADJUDICATE. Put this to the operator now. Present: (a) the finding and the repair that
   caused it; (b) whether that repair deleted or weakened something LOAD-BEARING -- an AC,
   a predicate, a guard, a LOCKED_REQUIREMENTS entry. A repair that makes a check
   unfalsifiable is the defect, not the fix; (c) your recommended resolution KIND.
3. RESOLVE. A repair edits the artifact to close findings on UNCHANGED scope -- that is
   what diverged, and doing it again is not a resolution. A resolution changes WHAT IS
   UNDER REVIEW:
     REVERT_REPAIR   put the artifact back to a state an earlier pass actually reviewed
     CUT_SCOPE       remove the contested scope; the artifact must get SMALLER
     CHANGE_APPROACH a different approach entirely, on the operator's authority
     RESTART_CYCLE   abandon the series, archive it, and start over
   Write the resolution record -- planning-artifacts/<sprint>-<artifact>-resolution-p<N>.md
   -- and then clear the pause flag. Writing that record is ALLOWED while paused; it is the
   one write the pause is waiting for.
   (FREEZE is NOT on this list. A hard block means CRITICALs rose in text that is ALREADY
   frozen, so freezing it again removes nothing and the gate can never pass over it.)
4. VERIFY. Run ONE pass on the resolved artifact, as the NEXT PASS NUMBER IN THIS SAME
   SERIES, declaring \`resolves_divergence:\`. That is the terminal clean pass Check 24
   requires. Do not start a new series -- the glob spans both and the pass numbers collide." \
    '{decision:"block",reason:$r,suppressOutput:true}'
  exit 0
fi

# -----------------------------------------------------------------------------
# Check 1: Pause flag (user-initiated pause)
# -----------------------------------------------------------------------------
if [ -f "$PAUSE_FLAG" ]; then
  {
    echo "## ${TIMESTAMP} -- ALLOWED_BY_PAUSE"
    echo "- Session: ${SESSION_ID}"
    echo "- Pause flag present; stop allowed"
    echo ""
  } >> "$LOG_FILE"
  # Reset block state -- pause-resume cycle counts as progress
  rm -f "$STATE_FILE"
  exit 0
fi

# -----------------------------------------------------------------------------
# Check 2: No active pipeline
# -----------------------------------------------------------------------------
if [ ! -f "$SNAPSHOT_FILE" ]; then
  # No pipeline; no state to track
  rm -f "$STATE_FILE"
  exit 0
fi

# -----------------------------------------------------------------------------
# Check 2b: A backgrounded wait-beat is live (Rule 29 yield-during-join, v0.81.0)
# -----------------------------------------------------------------------------
# The lead is permitted to END ITS TURN while a teammate join is outstanding, on
# the one condition that a backgrounded `wait-for-deliverable.sh` beat is genuinely
# sleeping -- because THAT process will exit and re-invoke this idle session (the
# harness re-invokes a session when a background task it spawned exits). Yielding
# there is not a stall: it is the bounded wait, off the foreground, and a queued
# operator lands on the very next turn instead of after a 120s blocking beat.
#
# The signal is a marker the script writes ONLY on its genuine-sleep path. We
# allow the stop iff the marker exists AND its epoch is still in the future.
# Every other case -- missing, unreadable, non-numeric, or expired -- FALLS
# THROUGH to the block below. The fail-safe direction is the pre-0.81.0 behavior
# (force-continue), never a new silent stall.
#
# THE MARKER IS A SHORT LEASE, NOT THE BEAT'S END TIME (v0.167.0). It once held
# the beat's worst-case end epoch, written once at arming; a SIGKILLed beat skips
# its EXIT trap, so this check kept allowing the yield for the whole remaining
# quantum with nothing left alive to re-invoke the lead. The script now re-stamps
# the marker every poll with `now + 3*POLL`, so a dead beat's marker expires in
# ~30s regardless of how long the quantum is -- which is what made raising the
# quantum from 120s to 600s safe. Nothing here changed: `epoch > now` reads a
# lease exactly as it read a promise.
if [ -f "$BEAT_MARKER" ]; then
  BEAT_DEADLINE=$(cat "$BEAT_MARKER" 2>/dev/null || echo "")
  if [[ "$BEAT_DEADLINE" =~ ^[0-9]+$ ]] && [ "$BEAT_DEADLINE" -gt "$NOW" ]; then
    {
      echo "## ${TIMESTAMP} -- ALLOWED_BY_LIVE_BEAT"
      echo "- Session: ${SESSION_ID}"
      echo "- Backgrounded wait-beat live until epoch ${BEAT_DEADLINE} (now ${NOW}); yield allowed"
      echo ""
    } >> "$LOG_FILE"
    # A live beat is forward progress, not a stall: reset the rapid-fire counter
    # so a burst of legitimate yields cannot trip the backoff and let a later
    # genuine stall through.
    rm -f "$STATE_FILE"
    exit 0
  fi
fi

# -----------------------------------------------------------------------------
# Read block state and compute rapid-fire status
# -----------------------------------------------------------------------------
LAST_TS=0
COUNTER=0

if [ -f "$STATE_FILE" ]; then
  LAST_TS=$(sed -n '1p' "$STATE_FILE" 2>/dev/null || echo "0")
  COUNTER=$(sed -n '2p' "$STATE_FILE" 2>/dev/null || echo "0")
  # Defensive: ensure numeric values
  [[ "$LAST_TS" =~ ^[0-9]+$ ]] || LAST_TS=0
  [[ "$COUNTER" =~ ^[0-9]+$ ]] || COUNTER=0
fi

DELTA=$((NOW - LAST_TS))

if [ "$DELTA" -lt "$RAPID_WINDOW_SECONDS" ]; then
  # Within rapid-fire window; same stall attempt
  COUNTER=$((COUNTER + 1))
else
  # Gap > window; progress happened (or first block)
  COUNTER=1
fi

# -----------------------------------------------------------------------------
# Check 3: Rapid-fire limit exceeded (genuine stall)
# -----------------------------------------------------------------------------
if [ "$COUNTER" -gt "$MAX_RAPID_BLOCKS" ]; then
  {
    echo "## ${TIMESTAMP} -- BACKOFF"
    echo "- Session: ${SESSION_ID}"
    echo "- ${MAX_RAPID_BLOCKS} consecutive rapid-fire blocks (within ${RAPID_WINDOW_SECONDS}s of each other); stall confirmed"
    echo "- Allowing stop. Investigate transcript for upstream cause."
    echo ""
  } >> "$LOG_FILE"
  rm -f "$STATE_FILE"
  exit 0
fi

# -----------------------------------------------------------------------------
# Default: Block the stop. Pipeline is active and autonomous.
# -----------------------------------------------------------------------------

# Extract current step and last gate from snapshot (best-effort).
# Snapshots may format as "current_step_file: <path>" or
# "- **current_step_file:** <path>". No line-start anchor; sed strips
# markdown bullet/bold and the leading label.
CURRENT_STEP=$(grep -iE "(current_step_file|current[ _]step|current[ _]phase)" "$SNAPSHOT_FILE" 2>/dev/null | head -1 | sed 's/^[^:]*://;s/^[-* ]*//;s/[-* ]*$//' || echo "")
LAST_GATE=$(grep -iE "(last_gate_passed|last[ _]gate)" "$SNAPSHOT_FILE" 2>/dev/null | head -1 | sed 's/^[^:]*://;s/^[-* ]*//;s/[-* ]*$//' || echo "")

REASON="Pipeline is active. You ended your turn without a tool call. This may be legitimate (presenting results mid-phase before the next action) or a stall.

CHECK BEFORE ACTING: Did you just complete a sub-skill and need to present its output before invoking the next one? If so, this is a FALSE POSITIVE — combine the presentation with the next tool call in your next response. Do NOT skip steps to avoid this hook.

