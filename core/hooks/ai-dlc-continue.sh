if [ ! -f "$SNAPSHOT_FILE" ]; then
  # No pipeline; no state to track
  rm -f "$STATE_FILE"
  exit 0
fi

# -----------------------------------------------------------------------------
# Check 2b: A backgrounded wait-beat is live (Rule 29 yield-during-join, v0.81.0)
# -----------------------------------------------------------------------------
# The lead is permitted to END ITS TURN while a teammate join is outstanding, on
# the one condition that a backgrounded `wait-for-deliverable.sh` beat is genuinely
# sleeping -- because THAT process will exit and re-invoke this idle session (the
# harness re-invokes a session when a background task it spawned exits). Yielding
# there is not a stall: it is the bounded wait, off the foreground, and a queued
# operator lands on the very next turn instead of after a 120s blocking beat.
#
# The signal is a marker the script writes ONLY on its genuine-sleep path. We
# allow the stop iff the marker exists AND its epoch is still in the future.
# Every other case -- missing, unreadable, non-numeric, or expired -- FALLS
# THROUGH to the block below. The fail-safe direction is the pre-0.81.0 behavior
# (force-continue), never a new silent stall.
#
# THE MARKER IS A SHORT LEASE, NOT THE BEAT'S END TIME (v0.167.0). It once held
# the beat's worst-case end epoch, written once at arming; a SIGKILLed beat skips
# its EXIT trap, so this check kept allowing the yield for the whole remaining
# quantum with nothing left alive to re-invoke the lead. The script now re-stamps
# the marker every poll with `now + 3*POLL`, so a dead beat's marker expires in
# ~30s regardless of how long the quantum is -- which is what made raising the
# quantum from 120s to 600s safe. Nothing here changed: `epoch > now` reads a
# lease exactly as it read a promise.
if [ -f "$BEAT_MARKER" ]; then
  BEAT_DEADLINE=$(cat "$BEAT_MARKER" 2>/dev/null || echo "")
  if [[ "$BEAT_DEADLINE" =~ ^[0-9]+$ ]] && [ "$BEAT_DEADLINE" -gt "$NOW" ]; then
    {
      echo "## ${TIMESTAMP} -- ALLOWED_BY_LIVE_BEAT"
      echo "- Session: ${SESSION_ID}"
      echo "- Backgrounded wait-beat live until epoch ${BEAT_DEADLINE} (now ${NOW}); yield allowed"
      echo ""
    } >> "$LOG_FILE"
    # THE BLOCK STATE IS DELIBERATELY NOT TOUCHED HERE, AND IT USED TO BE WIPED.
    # A removal of the state file sat on this line from v0.81.0 -- deliberately
    # NOT spelled out, because the s305 triage probe for this fix greps this
    # window for that exact command and a quotation of it reads as the defect.
    # It was reasoned as "a live beat is forward progress, so reset the
    # rapid-fire counter" -- but it took the TIMESTAMP with the counter, so the
    # next block read
    # `LAST_TS=0`, computed `DELTA = NOW - 0` (~1.79e9), took the `gap > window`
    # branch every time, and pinned the counter at 1. The backoff could then never
    # be reached by any sequence that put a beat between two blocks -- which is the
    # sequence a join-wait stall IS. Measured on the reference consumer's sprint
    # 305: `BLOCKED` 15, all 15 reading `rapid-fire 1/3`, `ALLOWED_BY_LIVE_BEAT`
    # 240, `BACKOFF` 0, against 170 wait-beat arms and 16.7 h inside join-wait
    # loops that nothing reported.
    #
    # PRESERVING `LAST_TS` WHILE STILL ZEROING THE COUNTER FIXES NOTHING, and that
    # is why the fix is a deletion rather than a rewrite. A zeroed counter makes
    # the next block `0 + 1 = 1` -- the identical value the epoch delta forced.
    # Driven both ways over four event sequences, the decision sequence came back
    # byte-identical; only the printed delta moved.
    #
    # THE CLOCK IS THE PROGRESS SIGNAL, so the counter needs no separate reset. A
    # beat that genuinely consumed time pushes `DELTA` past `RAPID_WINDOW_SECONDS`
    # and the `else` branch below resets the counter on its own. A beat that
    # returned instantly -- every target already on disk, one of the four ways the
    # block reason below says you can believe you have a beat and not have one --
    # consumes no time, so the counter keeps climbing and the stall is reported.
    #
    # A YIELD BURST STILL CANNOT TRIP THE BACKOFF. Nothing on this path increments
    # the counter; only a BLOCK does, twenty lines below. The v0.81.0 comment's
    # stated fear was of a state this code cannot reach.
    exit 0
  fi
fi

# -----------------------------------------------------------------------------
# Read block state and compute rapid-fire status
# -----------------------------------------------------------------------------
LAST_TS=0
COUNTER=0

if [ -f "$STATE_FILE" ]; then
  LAST_TS=$(sed -n '1p' "$STATE_FILE" 2>/dev/null || echo "0")
  COUNTER=$(sed -n '2p' "$STATE_FILE" 2>/dev/null || echo "0")
  # Defensive: ensure numeric values
  [[ "$LAST_TS" =~ ^[0-9]+$ ]] || LAST_TS=0
  [[ "$COUNTER" =~ ^[0-9]+$ ]] || COUNTER=0
fi

DELTA=$((NOW - LAST_TS))

if [ "$DELTA" -lt "$RAPID_WINDOW_SECONDS" ]; then
  # Within rapid-fire window; same stall attempt
  COUNTER=$((COUNTER + 1))
else
  # Gap > window; progress happened (or first block)
  COUNTER=1
fi

# -----------------------------------------------------------------------------
# Check 3: Rapid-fire limit exceeded (genuine stall)
# -----------------------------------------------------------------------------
if [ "$COUNTER" -gt "$MAX_RAPID_BLOCKS" ]; then
  {
    echo "## ${TIMESTAMP} -- BACKOFF"
    echo "- Session: ${SESSION_ID}"
    echo "- ${MAX_RAPID_BLOCKS} consecutive rapid-fire blocks (within ${RAPID_WINDOW_SECONDS}s of each other); stall confirmed"
    echo "- Allowing stop. Investigate transcript for upstream cause."
    echo ""
  } >> "$LOG_FILE"
  rm -f "$STATE_FILE"
  exit 0
fi

# -----------------------------------------------------------------------------
# Default: Block the stop. Pipeline is active and autonomous.
# -----------------------------------------------------------------------------

# Extract current step and last gate from snapshot (best-effort).
# Snapshots may format as "current_step_file: <path>" or
# "- **current_step_file:** <path>". No line-start anchor; sed strips
# markdown bullet/bold and the leading label.
CURRENT_STEP=$(grep -iE "(current_step_file|current[ _]step|current[ _]phase)" "$SNAPSHOT_FILE" 2>/dev/null | head -1 | sed 's/^[^:]*://;s/^[-* ]*//;s/[-* ]*$//' || echo "")
LAST_GATE=$(grep -iE "(last_gate_passed|last[ _]gate)" "$SNAPSHOT_FILE" 2>/dev/null | head -1 | sed 's/^[^:]*://;s/^[-* ]*//;s/[-* ]*$//' || echo "")

REASON="Pipeline is active. You ended your turn without a tool call. This may be legitimate (presenting results mid-phase before the next action) or a stall.

CHECK BEFORE ACTING: Did you just complete a sub-skill and need to present its output before invoking the next one? If so, this is a FALSE POSITIVE — combine the presentation with the next tool call in your next response. Do NOT skip steps to avoid this hook.

If you genuinely have no next action (HARD_BLOCK, PVC, handoff, retro commentary): create the pause flag (touch _bmad-output/pipeline-paused.flag).

IF YOU ARE WAITING ON A TEAMMATE, this block means NO LIVE WAIT-BEAT IS ARMED. Your turn may end during a join only while _bmad-output/.beat-inflight holds a future epoch, and the ONLY thing that writes it is scripts/ai-dlc/wait-for-deliverable.sh, on its sleeping path. Four ways you can believe you have a beat and not have one: (1) a hand-rolled sleep/stat/until loop — it writes no marker, and is the Rule 29 Check A violation gate Check 25 counts; (2) a foreground call — its exit trap clears the marker before your turn ends; (3) a call that RETURNED INSTANTLY because every target was already on disk; (4) a second beat chained into the same Bash call as another. Do NOT emit filler tool calls to get past this block. Re-arm the real beat and end your turn in the SAME response: Bash(run_in_background: true) scripts/ai-dlc/wait-for-deliverable.sh <path> [<path>...]

If you have a next action but emitted text first: pair the text with the tool call in your next response. Text + tool call = valid turn. Text alone = this hook fires.

IMPORTANT: This hook exists to prevent 'should I continue?' stalls (Rule 3). It does NOT mean 'skip the current step to produce a tool call faster.' Every numbered section in the current step file must be completed in full (Rule 4). If a section produces text output (party-mode results, failure classification, gate announcements), emit that text WITH the next section's tool call in the same response.

FIDELITY CHECK: Do NOT pattern-match on prior sprint execution. Re-read the current step file's numbered sections and execute each one literally. The pipeline is designed for fidelity, not throughput. Rushing through deploy-validate and retro — treating them as formalities because implementation feels 'done' — is the documented failure mode. Each section exists for a reason. Execute it."

if [ -n "$CURRENT_STEP" ]; then
  REASON="${REASON} Current step: ${CURRENT_STEP}."
fi
if [ -n "$LAST_GATE" ]; then
  REASON="${REASON} Last gate: ${LAST_GATE}."
fi

# -----------------------------------------------------------------------------
# Write updated state and log the block
# -----------------------------------------------------------------------------
echo "$NOW" > "$STATE_FILE"
echo "$COUNTER" >> "$STATE_FILE"

{
  echo "## ${TIMESTAMP} -- BLOCKED (rapid-fire ${COUNTER}/${MAX_RAPID_BLOCKS})"
  echo "- Session: ${SESSION_ID}"
  if [ -n "$CURRENT_STEP" ]; then
    echo "- Current step: ${CURRENT_STEP}"
  fi
  if [ -n "$LAST_GATE" ]; then
    echo "- Last gate: ${LAST_GATE}"
  fi
  # NEVER PRINT AN EPOCH AS A DELTA. With no previous block recorded `LAST_TS` is
  # 0 and `DELTA` is the current epoch -- a number that reads as an interval, is
  # off by fifty years, and was the visible symptom of the wiped-state defect
  # above. All 15 of sprint 305's blocks printed one (min `1787395192`) and it was
  # read as a long quiet gap rather than as a broken clock.
  if [ "$LAST_TS" -eq 0 ]; then
    echo "- Seconds since previous block: first block (no previous block recorded)"
  else
    echo "- Seconds since previous block: ${DELTA}"
  fi
  echo "- Reason returned to Claude: forced continuation (Rule 3)"
  echo ""
} >> "$LOG_FILE"

jq -n \
  --arg reason "$REASON" \
  '{
    decision: "block",
    reason: $reason,
    suppressOutput: true
  }'

exit 0