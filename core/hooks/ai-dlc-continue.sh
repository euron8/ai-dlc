# Beat-liveness marker written by scripts/ai-dlc/wait-for-deliverable.sh while a
# backgrounded wait-beat is genuinely sleeping (Check 2b, v0.81.0). Same dir and
# default as the script's AI_DLC_STATE_DIR (_bmad-output).
BEAT_MARKER="${LOG_DIR}/.beat-inflight"

# Rapid-fire thresholds
RAPID_WINDOW_SECONDS=30
MAX_RAPID_BLOCKS=3

# -----------------------------------------------------------------------------
# Read hook input
# -----------------------------------------------------------------------------
INPUT=$(cat)
SESSION_ID=$(echo "$INPUT" | jq -r '.session_id // empty')
TIMESTAMP=$(date -u +"%Y-%m-%dT%H:%M:%SZ")
NOW=$(date +%s)

# -----------------------------------------------------------------------------
# Seed log header if needed
# -----------------------------------------------------------------------------
mkdir -p "$LOG_DIR"
if [ ! -s "$LOG_FILE" ]; then
  cat > "$LOG_FILE" <<'EOF'
# Pipeline Flow Log

Records pipeline-level events: user pauses, Rule 3 enforcement, operator
acknowledgement denials, and rapid-fire stall detection. Generated by AI/DLC
hook scripts. Rotated per sprint at retro close (Rule 25(c)).

Event types:

- `USER_PAUSE`: the operator steered and the pipeline paused via flag file. TWO
  channels raise it and the entry's `Channel:` line names which: a typed message
  (UserPromptSubmit), or an AskUserQuestion answer carrying handoff intent. The
  second raises no UserPromptSubmit at all, so before it was routed a handoff
  asked for that way produced no USER_PAUSE, no flag, and no record that the
  operator had spoken
- `PAUSE_SKIPPED`: a UserPromptSubmit carried no operator prose, so no pause
  flag was created. The harness raises the event identically for a completed
  background task and for a human typing; this records the ones that were not
  a human, so a pause that never happened is distinguishable from one the lead
  already cleared
- `BLOCKED`: Stop event blocked; Rule 3 enforcement forced continue
- `ALLOWED_BY_PAUSE`: Stop event allowed because pause flag exists
- `PAUSE_QUESTION_IN_PROSE`: the pause flag was UP, the last line of the lead's
  reply was a question, and the turn carried no `AskUserQuestion`. The stop was
  allowed either way; the operator got one pointer line. A Rule 11(a) ambiguity
  question belongs in the tool, so a nonzero count is decisions the operator was
  asked for in prose and may never have seen — but the Production Validation
  Checkpoint and the retro commentary prompt are asked in prose by design and
  land here too. Read each one before counting it as a miss.
  The same predicate on the flag-DOWN side does NOT raise its own event: the
  verdict there is `BLOCKED`, and those rows carry `- Question in prose: yes`
- `ACK_DENIED`: a pipeline-advancing tool call was DENIED because an operator
  message was outstanding and unacknowledged (Rule 29). A nonzero count means
  the lead tried to execute straight through a waiting human and the hook --
  not the lead's judgment -- is what stopped it. Investigate each one.
- `BACKOFF`: rapid-fire stop attempts detected; stall confirmed
- `ESCALATION_UNDELIVERED`: a SendMessage returned `success:false`, so an
  operator-bound message was never delivered. The harness does NOT mark these
  as tool errors, which is why they fell through silently; a nonzero count
  means an escalation the lead believed it had sent did not arrive. Read the
  recorded target -- a failure to reach `parent` is subagent routing, not an
  operator escalation

Retro reviews this log to assess pipeline flow:

- High USER_PAUSE counts mean the user intervened often (normal for
  interactive sprints, concerning if unexpected)
- High PAUSE_SKIPPED counts are normal in a sprint with heavy background
  dispatch; a SUDDEN change in the USER_PAUSE:PAUSE_SKIPPED ratio is the
  signal worth reading
- High BLOCKED counts mean Rule 3 enforcement is doing work; without
  the hook the pipeline would have stalled
- BACKOFF entries indicate the pipeline actually got stuck and the
  hook exhausted its retry budget. Investigate the transcript around
  each BACKOFF to find the upstream cause.

Counting entries: one event is one `## <timestamp> -- <EVENT>` line. Count with
`grep -c '^## .*-- <EVENT>'`. A bare `grep -c <EVENT>` also matches this header,
which mentions every event name, so it over-reports — and the inflated number is
plausible enough that nothing about the result signals it counted documentation.

---

EOF
fi

# -----------------------------------------------------------------------------
# Check 0: Handoff resume-prompt guard
# -----------------------------------------------------------------------------
# Minimum mechanism (Rule 26(c)).
#   Failure caught: the operator asks for a handoff and the turn ENDS without a
#     copy-pasteable `/ai-dlc resume` block. The successor session then has no
#     entry line and the operator hand-writes one. A prose mandate
#     (`steps/handoff.md` step 4) did not hold on its own; this moves emission to
#     the harness. Presence alone is insufficient — a `/ai-dlc resume` mentioned in
#     prose, or in a blockquote with no delimiter lines, is not copy-pasteable — so
#     the guard checks FORMAT: the command line must sit BETWEEN two delimiter
#     lines.
#   False-positive cost: one extra turn when the operator's message merely mentions
#     handoff without requesting one. It self-clears through the rapid-fire backoff
#     below (MAX_RAPID_BLOCKS), so it can never wedge the pipeline.
#   Removal condition: retire when two consecutive sprints record zero
#     handoff-emission misses, or when the resume block is generated rather than
#     hand-authored.
#
# THE DELIMITER IS `-{4,}`, NOT AN EXACT COUNT, AND THAT IS THE WHOLE LESSON.
# The reference consumer carried this guard for months matching EXACTLY six hyphens
# (`^------$`) while `steps/handoff.md` step 4 has ALWAYS mandated four (`----`).
# Six-hyphen appears nowhere in core, at any sha. So the guard fired on handoffs
# that were CORRECT per the rulebook: the lead emitted `----` as instructed, got
# blocked, read a block message telling it to use `------`, and complied with the
# HOOK instead of the RULE. The enforcer quietly overruled the rule it was written
# to enforce — a check that fires on compliance, which is worse than no check.
# The invariant that matters is "the command line is delimited for copy-paste",
# never the hyphen count. Accept four or more; quote the rulebook's own template.
#
# A HANDOFF ALSO HAS TO BE AUDITABLE, WHICH IS A SECOND ARM ON THE SAME EVENT.
# `steps/handoff.md` step 1 says stop every in-flight teammate and record them in the
# snapshot; step 3 says the finalized snapshot carries that record. Measured on the
# reference consumer: a lead read a handoff request correctly, called one TaskStop, edited
# the snapshot and touched the pause flag -- and confirmed afterwards that there had been
# "no full teammate sweep, no commit, no push attempt". The resume block was the only thing
# anything checked, so the handoff looked complete. The successor session then inherits a
# snapshot whose In-Flight Teammates rows still read `in-flight` for teammates that are
# gone, which is the one state no later step can reconstruct.
#
# THE PREDICATE IS THE ROW THAT ALREADY EXISTS, not a new field: no row in the snapshot's
# `## In-Flight Teammates` section may still read `in-flight` at a handoff. Stopping a
# teammate and NOT recording it is what this catches, because step 1 requires the row be
# rewritten to `stopped` rather than deleted -- a deleted row is a lost record, and the
# successor cannot tell it from a teammate that never existed.
#
# FAIL-OPEN IN THREE PLACES, each because the absence is unambiguous: no snapshot at all
# (no pipeline), no In-Flight section (it AUTO-HEALS per route.md, so snapshots predating
# it are legal), and no rows (nothing was dispatched). The arm fires only on a row that
# positively says a teammate is still running.
#
# Fail-open: any transcript parse failure skips this check entirely.
TRANSCRIPT=$(echo "$INPUT" | jq -r '.transcript_path // empty')
HANDOFF_STATE="${LOG_DIR}/handoff-guard-state.txt"

# The handoff-intent vocabulary is NOT written here. It is declared once in
# schemas/pause-routing.json, because ai-dlc-answer-capture.sh needs the same set to route
# a handoff that arrives as an AskUserQuestion answer -- and a hand-maintained list of
# handoff phrasings in two files is two lists that drift, which ai-dlc-pause.sh's header
# already ruled on for its own list. `../schemas/` resolves in BOTH layouts from a hook
# (core/hooks/ upstream, .claude/hooks/ in a consumer); the env override is for fixtures
# driving a mutated copy from a temp directory.
#
# UNRESOLVED SKIPS THE WHOLE CHECK, and that silence is covered by a shipped fixture
# rather than by a log line: core/fixtures/handoff-resume-guard asserts the declaration
# resolves before it asserts anything about the guard, so an install that lost the schema
# fails at the consumer's own pre-push instead of quietly disarming the guard.
_hg_self="$(cd "$(dirname "$0")" && pwd)"
PAUSE_ROUTING_SCHEMA=""
for _prs in "${AI_DLC_PAUSE_ROUTING_SCHEMA:-}" \
            "${_hg_self}/../schemas/pause-routing.json" \
            "${PROJECT_DIR}/.claude/schemas/pause-routing.json" \
            "${PROJECT_DIR}/core/schemas/pause-routing.json"; do
  [ -n "$_prs" ] && [ -f "$_prs" ] && { PAUSE_ROUTING_SCHEMA="$_prs"; break; }
done
HANDOFF_INTENT_RE=""
HANDOFF_MENTION_RE=""
if [ -n "$PAUSE_ROUTING_SCHEMA" ]; then
  HANDOFF_INTENT_RE="$(jq -rj '.handoff_intent_pattern // ""' "$PAUSE_ROUTING_SCHEMA" 2>/dev/null)"
  HANDOFF_MENTION_RE="$(jq -rj '.handoff_mention_exclusion_pattern // ""' "$PAUSE_ROUTING_SCHEMA" 2>/dev/null)"
fi
# A DEDICATED SKIP FLAG, not a blanked $TRANSCRIPT. Check 0b reads $TRANSCRIPT too (it
# passes it to the cycle reader further down), so disarming Check 0 by clearing that
# variable would silently disarm an unrelated guard on the same event.
HANDOFF_VOCAB_OK=0
[ -n "$HANDOFF_INTENT_RE" ] && [ -n "$HANDOFF_MENTION_RE" ] && HANDOFF_VOCAB_OK=1

# THE TRANSCRIPT CANNOT SEE A HANDOFF ASKED FOR MID-TURN, AND THAT IS HOW THE REPORTED EPISODE
# BEGAN. A message typed while the lead is working is stored by the harness as a
# `queue-operation` record and never becomes a `message.role=="user"` entry, so `LAST_USER` below
# is whatever the harness raised instead. Measured on the reference consumer's session
# `21c0f322`: 18 queue-operation records, and the bare word the operator actually typed appears
# ZERO times as a user text message against a control of 3,296 non-empty ones. Every guard in
# this system keyed on the transcript was silent for that reason, this one included.
#
# `ai-dlc-pause.sh` is not, because it fires on UserPromptSubmit regardless of queuing and writes
# the request to the continuation log. So the DURABLE record of "the operator asked for a
# handoff" is on disk, and this is the only channel that survives both a queued message and a
# compaction. The log is read, never written, here.
#
# BOUNDED BY SESSION, WHICH IS ALSO THE DISCHARGE. The log is rotated per sprint (Rule 25(c)),
# so "any handoff row" would stay true for every later session in the sprint and would block
# ordinary work at its first Stop -- a guard that wedges correct sessions is worse than the
# defect. Keying on THIS session's rows bounds it to the conversation that was actually asked,
# needs no new log event, and ends when the session does. Measured on the same episode: the
# request at 13:06:31Z and every turn through 13:43:15Z carry one session id, and it changes at
# 13:45:38Z -- so the window closes exactly where it should.
#
# THE ROW'S OPERATOR-PROSE FIELD IS THE SIGNAL, NOT THE WHOLE ROW. `- Question` is lead-authored
# and `ai-dlc-answer-capture.sh` labels it "NOT the intent signal" in the row itself; letting it
# count would hand the lead a way to route its own guard. The patterns are the declared ones and
# are applied to the extracted VALUE -- the anchored `^ *hand[ -]?off *$` alternative cannot
# match a line still carrying its `- Prompt (first 120 chars): ` prefix, so a line-wise grep
# reads a real request as a non-instance and returns a clean, plausible zero.
# THE PREDICATE IS SOURCED, NOT SPELLED HERE. ai-dlc-recover.sh asks the same question after a
# compaction and the two answers must not drift; the library's header carries the three keys and
# the measurements behind them. Fail-open to today's behaviour if it is unreadable -- a Stop guard
# that cannot load a helper must not start blocking every Stop.
HANDOFF_ON_DISK=0
_AI_DLC_HP="$(dirname "${BASH_SOURCE[0]}")/ai-dlc-handoff-pending.sh"
if [ -r "$_AI_DLC_HP" ]; then
  . "$_AI_DLC_HP"
  if ai_dlc_handoff_pending "$LOG_DIR" "$SESSION_ID" "$PAUSE_ROUTING_SCHEMA"; then
    HANDOFF_ON_DISK=1
  fi
fi

if [ "$HANDOFF_VOCAB_OK" = "1" ] && [ -n "$TRANSCRIPT" ] && [ -f "$TRANSCRIPT" ]; then
  # ONE LINE, BECAUSE THE DECLARED PATTERNS ANCHOR ON `^` AND `$` AND grep ANCHORS PER LINE.
  # A multi-line message with a middle line reading `handoff` (or, since the final-sentence
  # alternative, ending `. handoff`) matched on that line alone and routed the whole message --
  # a pasted filing quoting the incident row would arm the guard. ai-dlc-pause.sh already
  # collapses newlines before writing the row key 3 reads, so this is the transcript reader
  # seeing the same text shape as the on-disk reader, not a new rule.
  LAST_USER=$({ jq -rs '[.[]|select(.message.role=="user")|.message.content|(if type=="string" then . else (map(select(.type=="text")|.text)|join(" ")) end)]|map(select(length>0))|last // ""' "$TRANSCRIPT" 2>/dev/null || echo ""; } | tr '\n' ' ')
  # LAST_ASST is reconstructed with join("") (NOT " "): the format check below is
  # line-anchored, and a streaming split of one text block into chunks can land a
  # boundary mid-line — join(" ") then corrupts a `----` marker into `-- --` and the
  # lead's own well-formed block false-blocks. join("") rejoins contiguous text so
  # marker lines survive. LAST_USER keeps join(" ") (substring regex, spacing-tolerant).
  LAST_ASST=$(jq -rs '[.[]|select(.message.role=="assistant")|.message.content|(if type=="string" then . else (map(select(.type=="text")|.text)|join("")) end)]|map(select(length>0))|last // ""' "$TRANSCRIPT" 2>/dev/null || echo "")

  # Match REQUEST-shaped phrasings only — "handoff"/"hand off" as a VERB, a terse
  # standalone "handoff", or "continue in a new session". Do NOT match incidental
  # NOUN mentions ("the handoff prompt", "handoff guard", the injected pipeline-control
  # context): those are discussion, not a request, and a bare-substring regex fires on
  # every one of them and spams the operator with a spurious resume prompt. The second
  # grep excludes any message that IS a resume prompt or talks ABOUT the mechanism.
  # ONCE ARMED, ARMED UNTIL SATISFIED -- WITHIN THIS SESSION AND WHILE THE PIPELINE IS PAUSED.
  # The marker arm below asserts the ABSENCE of the file that is key 1 of the predicate, so a
  # lead that runs step 5's `rm -f` before step 4's touch removes the only thing arming the guard
  # and the next Stop is not examined at all. Measured by driving this hook: marker present and
  # driver signal never touched -> BLOCK; marker cleared, driver still untouched -> ALLOW. So the
  # first armed Stop records the session id here, and every later Stop of the same session with
  # the pause flag still up is armed by that record until the guard is satisfied or the backoff
  # releases, both of which remove it. A Stop with the pause flag DOWN removes it too: the resume
  # path took the flag, so the handoff was abandoned and the record must not outlive that.
  HANDOFF_ARMED_FILE="${LOG_DIR}/.handoff-guard-armed"
  HANDOFF_STICKY=0
  if [ -f "$HANDOFF_ARMED_FILE" ]; then
    if [ -f "${LOG_DIR}/pipeline-paused.flag" ] && [ -n "$SESSION_ID" ] \
       && [ "$(head -n 1 "$HANDOFF_ARMED_FILE" 2>/dev/null)" = "$SESSION_ID" ]; then
      HANDOFF_STICKY=1
    else
      rm -f "$HANDOFF_ARMED_FILE"
    fi
  fi

  if [ "$HANDOFF_ON_DISK" = "1" ] || [ "$HANDOFF_STICKY" = "1" ] \
     || { grep -qiE "$HANDOFF_INTENT_RE" <<<"$LAST_USER" \
          && ! grep -qiE "$HANDOFF_MENTION_RE" <<<"$LAST_USER"; }; then
    [ -n "$SESSION_ID" ] && printf '%s\n' "$SESSION_ID" > "$HANDOFF_ARMED_FILE"

    RESUME_OK=$(printf '%s' "$LAST_ASST" | awk '
      /^[[:space:]]*-{4,}[[:space:]]*$/ { marks++; if (marks==1){opened=1;sawcmd=0} else if (marks>=2 && sawcmd){ok=1}; next }
      opened && /^[[:space:]]*\/ai-dlc[[:space:]]+resume[[:space:]]*$/ { sawcmd=1 }
      END { print (ok?"1":"0") }')

    # The teammate-sweep arm. Reads the LAST cell of every table row inside the
    # `## In-Flight Teammates` section, which is the `status` column route.md defines. The
    # last NON-EMPTY cell, because a markdown row's trailing pipe makes split() produce an
    # empty final field and a positional index would read that instead of the status.
    TEAMMATES_OK=1
    if [ -f "$SNAPSHOT_FILE" ]; then
      TEAMMATES_OK=$(awk '
        /^##[[:space:]]+In-Flight Teammates/ { inb=1; next }
        inb && /^##[[:space:]]/              { inb=0 }
        inb && /^[[:space:]]*\|/ {
          n = split($0, c, "|")
          last = ""
          for (i = n; i >= 1; i--) {
            gsub(/^[ \t]+/, "", c[i]); gsub(/[ \t]+$/, "", c[i])
            if (c[i] != "") { last = c[i]; break }
          }
          # LEADING TOKEN, NOT THE WHOLE CELL, and this was an equality test until
          # v0.483.0. check_inflight_status() in validate-artifact-budget.sh has always
          # split the leading token off, because the live rows of the reference consumer
          # carry `in-flight, since <ts>`, `in-flight, retrying Write` and `in-flight
          # (VERIFY pass, ...)`. Against `==` all three compared unequal, so `found`
          # stayed 0 and this guard ALLOWED a handoff with teammates genuinely still
          # running -- it fired only on the bare token. Measured on the four real forms:
          # 1 blocked, 3 allowed. The fixture could not see it because it seeded the bare
          # token, which is the form the reader already accepted.
          #
          # NO APOSTROPHE MAY APPEAR IN THIS COMMENT. It sits inside a single-quoted awk
          # program, so one closes the string and breaks the whole hook -- which is how
          # this comment was first written, and the fixture caught it.
          #
          # The delimiter set is the one the sibling uses: whitespace, comma or semicolon.
          tok = tolower(last)
          sub(/[[:space:],;].*$/, "", tok)
          if (tok == "in-flight") found = 1
        }
        END { print (found ? "0" : "1") }' "$SNAPSHOT_FILE" 2>/dev/null || echo 1)
      [ -n "$TEAMMATES_OK" ] || TEAMMATES_OK=1
    fi

    # THE PUSH ARM. Step 3 is the half of this procedure nothing has ever checked, and it is the
    # half that loses work: the resume line and the teammate sweep are both recorded IN the
    # conversation, so a lead that skips them is visible, while an unpushed branch looks exactly
    # like a pushed one from inside the session. Two prior releases fixed the push and neither
    # asserted it -- v0.434.0 corrected the COMMAND (a bare `git push` cannot succeed on a branch
    # that has never been pushed) and v0.438.0 corrected the resume line's ROUTER. Each removed
    # one route to the same end state and the state came back by another. This asserts the state.
    #
    # NO REMOTE AT ALL IS NOT A FAILURE, AND THAT NARROWING IS THE WHOLE FALSE-POSITIVE STORY.
    # `steps/handoff.md` step 3 names three ENVIRONMENTAL causes it forgives -- no remote
    # configured, offline, protected branch -- and tells the lead to report and continue. A repo
    # with no remote can never satisfy a push assertion, so blocking there would wedge every
    # handoff in a local-only tree. A branch with no upstream WHERE A REMOTE EXISTS is the
    # opposite case: it is precisely the state v0.434.0 was filed against, and `-u origin HEAD`
    # is prescribed to resolve it. Offline and protected-branch both leave the commits ahead and
    # DO block -- deliberately, because the operator needs to know the work is stranded, and the
    # remediation text below says to report it rather than to retry forever. The backoff releases
    # after MAX_RAPID_BLOCKS either way, so this can delay a handoff but cannot wedge one.
    PUSH_OK=1
    if command -v git >/dev/null 2>&1 && git -C "$PROJECT_DIR" rev-parse --git-dir >/dev/null 2>&1; then
      if [ -n "$(git -C "$PROJECT_DIR" remote 2>/dev/null)" ]; then
        if _up="$(git -C "$PROJECT_DIR" rev-parse --abbrev-ref '@{u}' 2>/dev/null)" && [ -n "$_up" ]; then
          _ahead="$(git -C "$PROJECT_DIR" rev-list --count '@{u}..HEAD' 2>/dev/null)"
          case "$_ahead" in
            ''|*[!0-9]*) : ;;                      # unreadable: do not invent a finding
            0) : ;;
            *) PUSH_OK=0 ;;
          esac
        else
          PUSH_OK=0                                 # remote exists, branch never published
        fi
      fi
    fi

    # THE DRIVER-SIGNAL ARM (step 4's touch) AND THE MARKER ARM (step 5's clear). Measured on
    # the reference consumer over every handoff its transcript corpus can score (39 of 120):
    # the `touch _bmad-output/.driver/handoff` was skipped on 20, the most-skipped step by six
    # times over the push, and the `rm -f` of the entry marker on 4 of the 17 in scope since it
    # was written. Neither had an arm; the three above did, and the skip rate of the guarded
    # steps fell to single digits while the unguarded one did not.
    #
    # `.driver/handoff` IS SAFE TO ASSERT HERE. The driver consumes it only when `.driver/idle`
    # is ALSO present, and idle is written by ai-dlc-driver-signal.sh, a Stop hook registered
    # after this one -- so at this seam a touched marker is still on disk. `touch` fails when
    # `.driver/` does not exist, which is why the remedy below says `mkdir -p` first and why
    # steps/handoff.md step 4 does too.
    #
    # PRESENCE IS NOT ENOUGH, AND THE REFERENCE CONSUMER IS THE PROOF. Only the session driver
    # ever removes this file, no driver is attached there, and `_bmad-output/.driver/handoff`
    # has sat on disk since the last handoff that touched it -- so a presence test is satisfied
    # forever on the very tree the 20-of-39 skip rate was measured on, and the arm for the
    # most-skipped step would have shipped inert. The reference is THIS handoff's step 3: the
    # finalized snapshot precedes the touch in the procedure, so a marker OLDER than the
    # snapshot predates this handoff. With no snapshot on disk there is no reference, and the
    # arm falls back to presence, stated. One known extra round: a lead that touched at step 4,
    # was blocked on the teammate arm and re-finalized the snapshot is told to touch again.
    #
    # THE TEST IS "SNAPSHOT NEWER THAN SIGNAL", NEVER "SIGNAL NEWER THAN SNAPSHOT". bash 3.2's
    # `-nt` compares whole seconds, and step 3's write and step 4's touch are adjacent tool
    # calls that routinely land in one second. Measured: two files created in the same second
    # are `-nt` each other in NEITHER direction, so the positive form would refuse a compliant
    # handoff and this negative form passes it; a signal back-dated to an earlier handoff is
