#!/usr/bin/env bash
. "$(cd "$(dirname "$0")/../lib" && pwd)/preamble.sh" || { echo "FIXTURE BROKEN: cannot source lib/preamble.sh" >&2; exit 2; }
# layer-entry-unreadable — prove that "I could not READ this entry" and "this entry has no
# such key" are two facts and not one. PC-S307.
#
# Usage: run.sh [path-to-validate-layer-entries.sh]
# Exit:  0 = every assertion holds, 1 = something regressed, 2 = the fixture cannot express
#        its own defect (FIXTURE BROKEN — see the precondition below).
#
# `fm()` reads one frontmatter scalar with one `awk` per file per key, and awk prints
# nothing in BOTH of these states:
#
#   ok.md         stdout=[x] rc=0        keyless.md    stdout=[] rc=0
#   unreadable.md stdout=[] rc=2         missing.md    stdout=[] rc=2
#
# Every caller read the value through `$( )` and threw the status away, so a read failure
# was reported as a missing key — a claim about a file's CONTENT made by a run that never
# saw the content. Measured on a consumer inside a freshly created `git worktree`: 20 false
# ERRORs against two demonstrably well-formed files, alongside `awk: can't open file` on
# stderr.
#
# BOTH DIRECTIONS, OR NEITHER. Parts 1 and 2 run the SAME file, generated by the same seed
# helper, into the same tree twice: once chmod 000, once readable with the receipt line
# removed. A validator that refuses everything it is handed produces Part 1's verdict and
# Part 2's verdict identically; only one that discriminates produces exit 2 with no finding
# for the first and exit 1 with an E17 for the second.
#
# WHY THERE ARE SEVEN TREES AND NOT ONE. The eight guarded call sites read in a
# fixed order over two populations, and an earlier guard pre-empts every later one on the
# same file:
#
#   site 1  census loop, `conforms_to`   ext + ovr   first reader of everything
#   site 2  overrides loop, `shadows`    ovr         first reader when LC_CV is ''
#   site 3  live-layer loop, `hooks`     ext         first reader when LC_CV is ''
#   site 4  extensions loop, `kind`      ext         always behind site 3
#   site 5  extensions loop, `extends`   ext         behind 4; permissive
#   site 6  extensions loop, `position`  ext         behind 5; permissive
#   site 7  extensions loop, `gate_types` ext        behind 6; permissive
#   site 8  reference loop, `shadows`    ext + ovr   LAST; acquittal, not permissive
#
# Three consequences the arms below are shaped by. Sites 2 onward are only observable where
# the census loop does not run -- `if [ -n "$LC_CV" ]` -- which is why two trees carry an
# unreadable contract_version. Site 8 reads BOTH populations last, so it is the backstop that
# records any permanently unreadable entry: no single guard owns the exit code, and what each
# one still buys is the false findings that would otherwise be printed. And site 4 is
# observable only once site 3 is gone.
#
# NO GUARD ABORTS ANY MORE, AND THAT IS BL-122. `entry_unreadable` records the path and
# `continue`s the caller's loop; the refusal is one `exit 2` at the END of the run, after every
# pass has emitted its findings about the entries the run COULD read and after a footer whose
# `unreadable=` field says how many it could not. The exit CODE is unchanged and the exit POINT
# moved. Two things follow for the arms here: an absent footer is no longer the shape of a
# refusal (three arms in Part 7 were keyed on it and now assert `unreadable=1` instead), and
# the property this fixture did not previously have a subject for -- findings about OTHER
# entries surviving -- gets Part 4b.
#
# SITES 5-8 CANNOT BE REACHED BY chmod 000 AT ALL, and Part 7 explains what replaces it.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"

pick() { for c in "$@"; do [ -n "$c" ] && [ -f "$c" ] && { printf '%s' "$c"; return; }; done; }
LINTER="$(pick "${1:-}" "$HERE/../../../scripts/ai-dlc/validate-layer-entries.sh" \
                        "$HERE/../../scripts/validate-layer-entries.sh" \
                        "$HERE/../../../core/scripts/validate-layer-entries.sh")"
[ -n "$LINTER" ] || { echo "FIXTURE BROKEN: cannot locate validate-layer-entries.sh" >&2; exit 2; }
# PRINTED, so the log names which copy of the subject the run loaded.
echo "layer-entry-unreadable: subject = $LINTER"
_LDIR="$(cd "$(dirname "$LINTER")" && pwd)"
echo "HERMETIC-CONSUMED ${_LDIR}/$(basename "$LINTER")"
[ -f "${_LDIR}/artifact-path-config.sh" ] && echo "HERMETIC-CONSUMED ${_LDIR}/artifact-path-config.sh"

# IN PROCESS (BL-878). The validator is SOURCED ONCE into this shell (its guard returns after defining vle_main), and
# every drive calls vle_main inside the subshell of the `$( )` that captures it, so its `exit`, `set -u`, EXIT trap and
# function definitions stay there. The sealed copy is sourced inside that same subshell, so its vle_main never replaces
# the shipped one here. The validator starts as a program only in the cli cells (cells.decl). A CORE FIXTURE SHIPS
# AHEAD OF ITS SUBJECT: a subject with neither its `vle_main() {` line nor the column-0 source guard predates the wrap
# and reads SKIP (exit 0, never an ok); exactly one half is a respelled subject and FAILs; a subject grep cannot READ
# (exit 2) is FIXTURE ERROR.
wrap_gate() { # wrap_gate <file> <entry> -> 0 wrapped, 3 predates the wrap, 1 one half only (FAIL printed), 2 unreadable
  local d g
  grep -q "^$2() {\$" "$1"; d=$?
  grep -qxF '[ "${BASH_SOURCE[0]}" = "$0" ] || return 0' "$1"; g=$?
  if [ "$d" -gt 1 ] || [ "$g" -gt 1 ]; then
    echo "FIXTURE ERROR: cannot read $1 (grep exit $d/$g), so the in-process wrap cannot be judged; nothing was asserted" >&2
    return 2
  fi
  [ "$d$g" = 00 ] && return 0
  [ "$d$g" = 11 ] && return 3
  if [ "$d" = 1 ]; then echo "  FAIL  $1 carries the column-0 source guard but no \`$2() {\` line -- a respelled subject this fixture cannot drive"
  else echo "  FAIL  $1 defines \`$2() {\` but carries no column-0 source guard -- a respelled subject; sourcing it would run $2 in this shell"; fi
  return 1
}
wrap_gate "$LINTER" vle_main; g_vle=$?
[ "$g_vle" = 2 ] && exit 2
[ "$g_vle" = 1 ] && { echo "layer-entry-unreadable: 1 FAILED"; exit 1; }
[ "$g_vle" = 3 ] && { echo "SKIP: subject predates the in-process wrap"; exit 0; }

ROOT="$(bash "$HERE/seed.sh")"
[ -n "$ROOT" ] && [ -d "$ROOT" ] || { echo "FIXTURE BROKEN: seed produced no sandbox" >&2; exit 2; }
TMP="$(mktemp -d "${TMPDIR:-/tmp}/layer-entry-unreadable-mut.XXXXXX")"
# CHMOD BACK BEFORE THE rm. A 000 file inside a directory `rm -rf` must unlink is fine on
# this platform and is not fine everywhere, and a fixture that leaves its sandbox behind on
# some machines is a fixture that fails somewhere nobody is looking.
cleanup() { chmod -R u+rwX "$ROOT" 2>/dev/null; rm -rf "$ROOT" "$TMP"; }
trap cleanup EXIT

CONS="$ROOT/consumer"; UNR="$ROOT/unreadable"; KEY="$ROOT/keyless"
OVRT="$ROOT/nolc-ovr"; EXTT="$ROOT/nolc-ext"

# --------------------------------------------------------------------------------------
# PRECONDITION — a fixture whose tree cannot EXPRESS the defect proves nothing
# --------------------------------------------------------------------------------------
# `chmod 000` does not make a file unreadable for root, and it does not make one unreadable
# on a filesystem mounted without permissions. Under either, every arm below runs against a
# perfectly readable entry and reports PASS having asserted nothing at all. This is the one
# state the fixture must call BROKEN rather than clean.
for _s in "$UNR/.claude/skills/ai-dlc/extensions/subject.md" \
          "$OVRT/.claude/skills/ai-dlc/overrides/subject-ovr.md" \
          "$EXTT/.claude/skills/ai-dlc/extensions/subject-ext.md"; do
  [ -f "$_s" ] || { echo "FIXTURE BROKEN: seed did not write $_s" >&2; exit 2; }
  if cat "$_s" >/dev/null 2>&1; then
    echo "FIXTURE BROKEN: $_s is STILL READABLE after chmod 000 — this fixture's subject is" >&2
    echo "  a read failure, and on this machine it cannot produce one (running as root, or a" >&2
    echo "  filesystem with no permission bits). Every assertion below would pass vacuously." >&2
    exit 2
  fi
done
# And the CONTROL for that loop: a file seeded the same way, deliberately left readable. A
# `cat` that fails for some unrelated reason -- a wrong path, a dead sandbox -- would satisfy
# the check above on every file and report the same clean line.
cat "$CONS/.claude/skills/ai-dlc/extensions/current-a.md" >/dev/null 2>&1 || {
  echo "FIXTURE BROKEN: a deliberately READABLE seeded entry could not be read either, so the" >&2
  echo "  unreadability check above proves nothing about permissions." >&2; exit 2; }

# shellcheck source=/dev/null
. "$HERE/../lib/report.sh" || { echo "FIXTURE ERROR: lib/report.sh not found" >&2; exit 2; }
. "$HERE/../lib/mutant.sh" || { echo "FIXTURE ERROR: lib/mutant.sh not found" >&2; exit 2; }
fx_inproc "$LINTER"
. "$LINTER" || { echo "FIXTURE ERROR: sourcing $LINTER failed" >&2; exit 2; }
declare -F vle_main > /dev/null || { echo "FIXTURE ERROR: sourcing $LINTER defined no vle_main" >&2; exit 2; }
say() { if [ "$1" = 1 ]; then ok "$2"; else bad "$2"; fi; }

# NO run() HELPER, deliberately. `OUT="$(run ...)"` evaluates the helper in a SUBSHELL, so an
# rc it assigns to a global is discarded and every exit-code assertion below would read a
# stale 0. Each call site captures `$?` on the same line as its own command substitution.

# footer_field <output> <name> -- value of name= on the LAYER_CONFORMANCE line.
# HERE-STRING, not a pipe: the awk program `exit`s at the first match, so under pipefail a
# large enough value would make the writer die on EPIPE and the field read as absent.
footer_field() {
  awk -v k="$2" '
    /^LAYER_CONFORMANCE / { for (i=2; i<=NF; i++) { split($i, p, "="); if (p[1] == k) { print p[2]; exit } } }' <<<"$1"
}
# fatal_for <output> <path-suffix> -- rc 0 when a FATAL line names that file.
# Two greps over a captured string rather than a pipeline, and the trailing quote is part of
# the needle so `subject.md'` cannot be satisfied by `subject-ext.md'`.
fatal_for() {
  local _f; _f="$(grep -F 'could not READ' <<<"$1")"
  [ -n "$_f" ] && grep -Fq "$2'" <<<"$_f"
}
# errs_naming <output> <path-suffix> -- how many ERROR lines name that file
errs_naming() {
  awk -v p="$2" 'index($0,"ERROR")==1 && index($0,p)>0 { n++ } END { print n+0 }' <<<"$1"
}
has() { grep -Fq "$2" <<<"$1"; }

echo "layer-entry-unreadable:"

# --------------------------------------------------------------------------------------
# Part 1 — an entry that cannot be READ produces a refusal and NO finding about it
# --------------------------------------------------------------------------------------
UNR_OUT="$( ( fx_inproc "$LINTER"; vle_main "$UNR" ) 2>&1)"; UNR_RC=$?
# EXIT 2 IS UNMOVED AS A VERDICT AND MOVED AS AN EVENT, and both halves are asserted. The code
# is the same one; what changed is that it is taken after every pass has run, so the footer is
# now present on this tree where it used to be absent. Requiring the footer HERE is what stops
# a fix that reverts to the immediate abort from passing this arm — that fix produces the same
# exit code and no footer at all.
say "$([ "$UNR_RC" -eq 2 ] && [ "$(footer_field "$UNR_OUT" errors)" = 0 ] && echo 1 || echo 0)" \
  "an unreadable entry exits 2 — the 'could not run' code — AFTER a completed run that printed its footer"
say "$(fatal_for "$UNR_OUT" 'extensions/subject.md' && echo 1 || echo 0)" \
  "the FATAL names the file it could not read, so the operator is told WHICH entry"
say "$([ "$(errs_naming "$UNR_OUT" 'extensions/subject.md')" -eq 0 ] && echo 1 || echo 0)" \
  "ZERO ERROR lines name that file — no claim about content this run never saw"

# --------------------------------------------------------------------------------------
# Part 2 — the discriminating twin: same file, readable, key genuinely absent
# --------------------------------------------------------------------------------------
# A validator that refused every entry handed to it would satisfy Part 1 exactly. This is
# the input that separates the two, and it differs from Part 1's by one chmod and one line.
KEY_OUT="$( ( fx_inproc "$LINTER"; vle_main "$KEY" ) 2>&1)"; KEY_RC=$?
say "$([ "$KEY_RC" -eq 1 ] && echo 1 || echo 0)" \
  "a genuinely keyless entry exits 1 — a finding, not a refusal"
say "$(has "$KEY_OUT" "extensions/subject.md: missing 'conforms_to:'" && echo 1 || echo 0)" \
  "and it still takes its ordinary E17 missing-key ERROR, named"
say "$(! grep -Fq 'could not READ' <<<"$KEY_OUT" && echo 1 || echo 0)" \
  "the keyless twin draws no FATAL, so the refusal is keyed on the READ and not on the key"

# --------------------------------------------------------------------------------------
# Part 3 — the baseline this all sits on
# --------------------------------------------------------------------------------------
CONS_OUT="$( ( fx_inproc "$LINTER"; vle_main "$CONS" ) 2>&1)"; CONS_RC=$?
say "$([ "$CONS_RC" -eq 0 ] && [ "$(footer_field "$CONS_OUT" entries)" = 2 ] \
       && [ "$(footer_field "$CONS_OUT" errors)" = 0 ] && echo 1 || echo 0)" \
  "a readable, well-formed consumer exits 0 with the footer counting both its entries"
# `unreadable=` IN BOTH DIRECTIONS, IN THE SAME RUN. A field hardcoded to 1 satisfies every
# other arm in this fixture, all of which run on a tree that HAS an unreadable entry; the clean
# tree is the only input that separates a counted field from a printed constant. Asserted as
# `= 0` and not merely non-empty, because an empty value would also pass an absence test on a
# subject that never learned the field at all.
say "$([ "$(footer_field "$CONS_OUT" unreadable)" = 0 ] \
       && [ "$(footer_field "$UNR_OUT" unreadable)" = 1 ] && echo 1 || echo 0)" \
  "the footer's unreadable= counts 0 on the clean tree and 1 on the sealed one — a count, not a constant"

# --------------------------------------------------------------------------------------
# Part 4 — the two trees the later guards are the first reader on
# --------------------------------------------------------------------------------------
# `contract_version` is made unreadable rather than the contract deleted: the validator
# ERRORs, sets LC_CV empty and CARRIES ON, which is the reachable state in which the census
# loop is skipped.
OVR_OUT="$( ( fx_inproc "$LINTER"; vle_main "$OVRT" ) 2>&1)"; OVR_RC=$?
if [ "$OVR_RC" -eq 2 ] && fatal_for "$OVR_OUT" 'overrides/subject-ovr.md' \
   && [ "$(errs_naming "$OVR_OUT" 'overrides/subject-ovr.md')" -eq 0 ]; then
  ok "an unreadable OVERRIDE refuses too, with no E1 about frontmatter nobody read"
else
  bad "an unreadable OVERRIDE refuses too, with no E1 about frontmatter nobody read"
fi
EXT_OUT="$( ( fx_inproc "$LINTER"; vle_main "$EXTT" ) 2>&1)"; EXT_RC=$?
if [ "$EXT_RC" -eq 2 ] && fatal_for "$EXT_OUT" 'extensions/subject-ext.md' \
   && ! has "$EXT_OUT" 'EMPTY resolvability set' \
   && [ "$(errs_naming "$EXT_OUT" 'extensions/subject-ext.md')" -eq 0 ]; then
  ok "an unreadable EXTENSION refuses before the resolvability set is judged, so E16 makes no claim"
else
  bad "an unreadable EXTENSION refuses before the resolvability set is judged, so E16 makes no claim"
fi

# --------------------------------------------------------------------------------------
# Part 4b — SURVIVAL: an unreadable entry does not suppress findings about its siblings
# --------------------------------------------------------------------------------------
# BL-122's subject. Every arm above asks what the run says ABOUT the unreadable file; this
# asks what it still says about the OTHER files, which is the property the immediate exit
# destroyed. Measured at HEAD on this fixture's own trees, worst case lost 7 of 7 ERRORs and
# both WARNs before printing anything.
#
# BOTH SORT POSITIONS, AND THE SECOND IS NOT A DUPLICATE. `layer_files()` sorts, so the seal's
# basename decides whether the readable sibling has already been visited when the loop meets
# it. A candidate whose sole error was `break` for `continue` passes `partial-zz` — nothing
# sorts after the seal there, so no finding is lost — and fails `partial-aa`. An arm run at
# one position only cannot tell that fix from this one.
#
# THE CONTROL IS THE BASELINE, NOT AN ASSUMPTION. A tree whose readable sibling drew no finding
# in the first place would satisfy "the finding survived" by having nothing to lose, and would
# read identically to a working fix. Each position asserts its own unsealed row count first,
# from the same tree, and requires the sealed run to reproduce it.
for _p in aa zz; do
  _pt="$ROOT/partial-$_p"
  _seal="$_pt/.claude/skills/ai-dlc/extensions/${_p}-sealed.md"
  # The seal must have taken here too. Without this the two arms below pass on a tree whose
  # sealed file is perfectly readable, which is the vacuous state the preamble refuses globally
  # — and these two trees are seeded after that loop's list was written.
  if cat "$_seal" >/dev/null 2>&1; then
    bad "FIXTURE BROKEN: partial-$_p's seal did not take, so its survival arms are vacuous"
    bad "FIXTURE BROKEN: partial-$_p (second arm not run for the same reason)"
    continue
  fi
  PT_OUT="$( ( fx_inproc "$LINTER"; vle_main "$_pt" ) 2>&1)"; PT_RC=$?
  # `no-receipt.md` declares no conforms_to, so the CENSUS LOOP — the loop the first guarded
  # read sits in, and the one whose abort this entry is about — raises an E17 naming it. A
  # finding raised by a later pass would survive a fix that only repaired the census.
  PT_SIB="$(errs_naming "$PT_OUT" 'extensions/no-receipt.md')"
  if [ "$PT_RC" -eq 2 ] && [ "$PT_SIB" -ge 1 ] \
     && [ "$(footer_field "$PT_OUT" unreadable)" = 1 ] \
     && [ -n "$(footer_field "$PT_OUT" errors)" ]; then
    ok "partial-$_p: the readable sibling's finding SURVIVES the unreadable one, the footer prints, and the run still refuses"
  else
    bad "partial-$_p: the readable sibling's finding SURVIVES the unreadable one, the footer prints, and the run still refuses"
  fi
  # ATTRIBUTION, and it is the half that separates this from `defer-the-exit-only`. The sealed
  # entry draws no ERROR or WARN row of its own: the run makes no claim about content it never
  # read, and every row in that count is about a file it did.
  say "$([ "$(errs_naming "$PT_OUT" "extensions/${_p}-sealed.md")" -eq 0 ] \
         && fatal_for "$PT_OUT" "extensions/${_p}-sealed.md" && echo 1 || echo 0)" \
    "partial-$_p: and ZERO rows name the sealed entry, which is instead named by the end-of-run FATAL"
done

# --------------------------------------------------------------------------------------
# Part 5 — cwd invariance, asserted rather than assumed
# --------------------------------------------------------------------------------------
# A fixture green only from the repo root may be asserting nothing, and this one resolves
# both its subject and its seed from `$HERE`. Re-run the same subject on the same tree from
# `/` and require the identical verdict; a subject that resolved anything from the process
# working directory answers differently here.
CWD_OUT="$( ( cd / || exit 2; fx_inproc "$LINTER"; vle_main "$UNR" ) 2>&1)"; CWD_RC=$?
say "$([ "$CWD_RC" -eq "$UNR_RC" ] && fatal_for "$CWD_OUT" 'extensions/subject.md' && echo 1 || echo 0)" \
  "the same verdict and the same FATAL when the subject is invoked from / — cwd-invariant"

# --------------------------------------------------------------------------------------
# Part 7 — the reads whose EMPTY value is PERMISSIVE
# --------------------------------------------------------------------------------------
# The first four guards all sit on reads whose empty value MANUFACTURES a finding, so a
# failure there is loud and wrong. These four are the opposite class: every arm consuming
# them is gated on the value being non-empty, so an empty read reads as "key absent" and
# absent is the CONFORMING answer. A read failure does not add a finding, it DELETES one —
# and the count in the footer still looks plausible, which is why the existing arms (exit 2,
# zero ERRORs naming the file) cannot catch it. What catches it is asserting the specific
# rows are THERE readable and that the run REFUSES sealed.
#
# THESE SITES CANNOT BE REACHED BY chmod 000. Every earlier guard reads the same file first
# and refuses, so a permanently unreadable entry never gets here. The failure these guards
# exist for is a read that fails PART WAY THROUGH a run — the git-worktree race the filing
# names — so the fixture reproduces that directly: a copy of the subject whose `fm()`
# returns for one file and one key set exactly what `awk` returns when it cannot open a
# file. That pair is not invented; C2 below measures it off the shipped `fm()` itself.
PERM="$ROOT/permissive"; CITE="$ROOT/citation"
PERM_SUBJ="$PERM/.claude/skills/ai-dlc/extensions/role-entry.md"
CITE_SUBJ="$CITE/.claude/skills/ai-dlc/extensions/cite-ext.md"

# nrows <output> <code> <path-suffix> -- how many finding rows carry that code AND name that file
nrows() {
  awk -v c="$2" -v p="$3" '$1 ~ /^(ERROR|WARN)$/ && $2 == c && index($0, p) > 0 { n++ } END { print n+0 }' <<<"$1"
}
# sr <script> <seal-keys> <tree> <seal-file> -- run, leaving SR_OUT/SR_RC. NOT via `X="$(sr …)"`,
# which would evaluate the whole helper in a subshell and discard the rc it assigns. IN PROCESS: the
# shipped subject is already sourced; any other <script> (the sealed copy) is sourced inside the
# capturing subshell, so its vle_main and the FX_SEAL_* values it reads never reach this shell.
sr() { SR_OUT="$( ( fx_inproc "$1"; if [ "$1" != "$LINTER" ]; then . "$1" || exit 2; fi; FX_SEAL_FILE="$4"; FX_SEAL_KEYS="$2"; vle_main "$3" ) 2>&1)"; SR_RC=$?; }

# --- C1: the tree can EXPRESS the defect. Without this every arm below is vacuous. --------
# The first probe of this defect seeded no `steps/retro.md`, so the entry took an E5 and
# `continue`d before the arms under test ever ran — a clean-looking zero that proved nothing.
sr "$LINTER" '' "$PERM" ''
say "$([ "$SR_RC" -eq 1 ] \
       && [ "$(nrows "$SR_OUT" E11 'extensions/role-entry.md')" -eq 1 ] \
       && [ "$(nrows "$SR_OUT" E12 'extensions/role-entry.md')" -eq 1 ] \
       && [ "$(nrows "$SR_OUT" E13 'extensions/role-entry.md')" -eq 1 ] \
       && [ "$(nrows "$SR_OUT" E14 'extensions/role-entry.md')" -eq 1 ] && echo 1 || echo 0)" \
  "READABLE, the role entry draws all four permissive-arm findings — the tree reaches the sites"
PERM_ERRS="$(footer_field "$SR_OUT" errors)"

# --- C2: the seal is FAITHFUL, measured off the shipped fm() and in BOTH directions -------
# A hand-written stand-in is a second implementation whose bugs nobody finds, so the pair the
# seal returns is taken from the real function against real files. Both directions, because a
# stand-in that failed on everything would satisfy the first half alone. (Measured while
# building this: `awk 'END{}'` on a 000 file exits 0, not 2 — a program with no input-reading
# rule never opens its operand. The shipped grammar is the only faithful probe.)
FM_BODY="$(sed -n '/^fm() {/,/^}/p' "$LINTER")"
{ printf '%s\n' "$FM_BODY"; printf 'fm "$1" "$2"\n'; } > "$TMP/fmprobe.sh"
FM_U_OUT="$(bash "$TMP/fmprobe.sh" "$UNR/.claude/skills/ai-dlc/extensions/subject.md" conforms_to 2>/dev/null)"; FM_U_RC=$?
FM_K_OUT="$(bash "$TMP/fmprobe.sh" "$KEY/.claude/skills/ai-dlc/extensions/subject.md" conforms_to 2>/dev/null)"; FM_K_RC=$?
say "$([ -n "$FM_BODY" ] && [ -z "$FM_U_OUT" ] && [ "$FM_U_RC" -ne 0 ] \
       && [ -z "$FM_K_OUT" ] && [ "$FM_K_RC" -eq 0 ] && echo 1 || echo 0)" \
  "the shipped fm() answers empty/non-zero on an unreadable file and empty/ZERO on a keyless one — the pair the seal imitates"

# --- build the sealed copy ----------------------------------------------------------------
mkseal() { # mkseal <in> <out> -- fm() returns empty with rc 2 for one file and a named key set
  awk '
    /^fm\(\) \{/ && !d {
      print
      print "  if [ -n \"${FX_SEAL_FILE:-}\" ] && [ \"$1\" = \"$FX_SEAL_FILE\" ]; then"
      print "    case \" ${FX_SEAL_KEYS:-} \" in *\" $2 \"*) return 2 ;; esac"
      print "  fi"
      d = 1; next
    }
    { print }' < "$1" > "$2"
}
mkseal "$LINTER" "$TMP/sealed.sh"
# The copy every sr call SOURCES carries the subject's own path suffix, so its in-process passes count on the
# fixture's one `inproc:` row (J7). The parse check reads sealed.sh, whose name no subject row matches.
SEALED="$TMP/core/scripts/validate-layer-entries.sh"
SEAL_OK=0
if cmp -s "$LINTER" "$TMP/sealed.sh"; then
  bad "SEAL: the injection matched nothing, so every arm below would run the shipped subject"
elif ! bash -n "$TMP/sealed.sh" 2>/dev/null; then
  bad "SEAL: the sealed copy does not parse, so its silence would be a syntax error"
elif ! { mkdir -p "$(dirname "$SEALED")" && cp "$TMP/sealed.sh" "$SEALED"; }; then
  echo "FIXTURE BROKEN: could not place the sealed copy at $SEALED" >&2; exit 2
else
  # --- C3: and it is INERT until armed. -------------------------------------------------
  # Compared on rc and the ERROR rows rather than on whole output: a copy resolves
  # `artifact-path-config.sh` from beside ITSELF, so W11's wording differs in every copy in
  # this directory. That difference reaches no arm, and asserting on it would fail here for
  # a reason that has nothing to do with the seal.
  sr "$SEALED" '' "$PERM" ''
  say "$([ "$SR_RC" -eq 1 ] && [ "$(footer_field "$SR_OUT" errors)" = "$PERM_ERRS" ] \
         && [ "$(nrows "$SR_OUT" E11 'extensions/role-entry.md')" -eq 1 ] \
         && [ "$(nrows "$SR_OUT" E14 'extensions/role-entry.md')" -eq 1 ] && echo 1 || echo 0)" \
    "SEAL CONTROL: unarmed, the sealed copy reproduces the shipped verdict and error count"
  SEAL_OK=1
fi

if [ "$SEAL_OK" = 1 ]; then
  # --- C4-C6: armed, the shipped guards REFUSE at each permissive site -------------------
  # Later sites legitimately emit the findings the earlier arms already produced before the
  # abort, so unlike Part 1 these do NOT assert zero ERRORs naming the file. What they assert
  # is the refusal: no verdict is issued over a file this run could not finish reading.
  #
  # THE THIRD CONJUNCT WAS `[ -z "$(footer_field … errors)" ]` — an absent footer — and it was
  # asserting the ABORT, not the refusal. The abort is what BL-122 removed: the run now finishes
  # every pass and prints the footer, then refuses. An absent footer is no longer the shape of a
  # refusal, and keeping the arm would have held the defect in place.
  #
  # `unreadable=1` REPLACES IT, and it is the stronger conjunct rather than a weaker one. An
  # absent footer says only that the run stopped somewhere; this says the run finished AND
  # counted this entry as one it could not read. The footer is present and it does not pass
  # judgement on the sealed file — that second half is what the `unreadable=` field states, and
  # what P4 of the ledger receipt asserts separately in row terms.
  for _k in extends position gate_types; do
    sr "$SEALED" "$_k" "$PERM" "$PERM_SUBJ"
    if [ "$SR_RC" -eq 2 ] && fatal_for "$SR_OUT" 'extensions/role-entry.md' \
       && [ "$(footer_field "$SR_OUT" unreadable)" = 1 ]; then
      ok "a mid-run read failure on '$_k' REFUSES — exit 2, named, and a footer declaring unreadable=1"
    else
      bad "a mid-run read failure on '$_k' REFUSES — exit 2, named, and a footer declaring unreadable=1"
    fi
  done

  # --- C7/C8: the acquittal site, which is the odd one of the eight ---------------------
  sr "$LINTER" '' "$CITE" ''
  say "$([ "$SR_RC" -eq 0 ] && [ "$(nrows "$SR_OUT" W12 'extensions/cite-ext.md')" -eq 0 ] && echo 1 || echo 0)" \
    "READABLE, the cited entry is ACQUITTED by its own shadows anchor — no W12, exit 0"
  sr "$SEALED" shadows "$CITE" "$CITE_SUBJ"
  if [ "$SR_RC" -eq 2 ] && fatal_for "$SR_OUT" 'extensions/cite-ext.md'; then
    ok "and a mid-run read failure on 'shadows' REFUSES rather than judging the citation"
  else
    bad "and a mid-run read failure on 'shadows' REFUSES rather than judging the citation"
  fi
fi

# --------------------------------------------------------------------------------------
# The cli cells (cells.decl): the validator run as a PROGRAM once per distinct CLI outcome
# this fixture reads (exit 2 the unreadable entry, exit 1 the keyless twin, exit 0 the clean
# consumer), each compared byte for byte with the in-process call on the same input (stdout,
# stderr and exit separately) and asserting its own outcome.
# --------------------------------------------------------------------------------------
EQ="$TMP/eq"; mkdir -p "$EQ" || exit 2
eqv() { # eqv <cell-id> <args...> -> $EQ/<id>.{ip,cl}.{out,err,rc}; 0 when the two answers are identical
  local id="$1"; shift
  ( fx_inproc "$LINTER"; vle_main "$@" ) > "$EQ/$id.ip.out" 2> "$EQ/$id.ip.err"; echo "$?" > "$EQ/$id.ip.rc"
  FXCELL="$id" bash "$LINTER" "$@" > "$EQ/$id.cl.out" 2> "$EQ/$id.cl.err"; echo "$?" > "$EQ/$id.cl.rc"
  cmp -s "$EQ/$id.ip.out" "$EQ/$id.cl.out" && cmp -s "$EQ/$id.ip.err" "$EQ/$id.cl.err" && cmp -s "$EQ/$id.ip.rc" "$EQ/$id.cl.rc"
}
eq_twin() { printf 'in-process rc=%s out=[%s] err=[%s] / program rc=%s out=[%s] err=[%s]' "$(cat "$EQ/$1.ip.rc")" \
  "$(tail -2 "$EQ/$1.ip.out")" "$(head -2 "$EQ/$1.ip.err")" "$(cat "$EQ/$1.cl.rc")" "$(tail -2 "$EQ/$1.cl.out")" "$(head -2 "$EQ/$1.cl.err")"; }
if eqv cli-refuse "$UNR" && [ "$(cat "$EQ/cli-refuse.cl.rc")" = 2 ] && grep -qF 'could not READ' "$EQ/cli-refuse.cl.out" "$EQ/cli-refuse.cl.err"; then
  ok "cli-refuse: the program refuses the unreadable entry exactly as the in-process call does (stdout, stderr, exit 2)"
else bad "cli-refuse: the program and the in-process call differ, or the outcome is not exit 2 with its FATAL ($(eq_twin cli-refuse))"; fi
if eqv cli-fail "$KEY" && [ "$(cat "$EQ/cli-fail.cl.rc")" = 1 ] && grep -qF "extensions/subject.md: missing 'conforms_to:'" "$EQ/cli-fail.cl.out"; then
  ok "cli-fail: the program refuses the keyless entry exactly as the in-process call does (stdout, stderr, exit 1)"
else bad "cli-fail: the program and the in-process call differ, or the outcome is not exit 1 with the E17 row ($(eq_twin cli-fail))"; fi
if eqv cli-pass "$CONS" && [ "$(cat "$EQ/cli-pass.cl.rc")" = 0 ] && grep -q '^LAYER_CONFORMANCE v1 .* errors=0 ' "$EQ/cli-pass.cl.out"; then
  ok "cli-pass: the program passes the clean consumer exactly as the in-process call does (stdout, stderr, exit 0)"
else bad "cli-pass: the program and the in-process call differ, or the outcome is not exit 0 with errors=0 ($(eq_twin cli-pass))"; fi

